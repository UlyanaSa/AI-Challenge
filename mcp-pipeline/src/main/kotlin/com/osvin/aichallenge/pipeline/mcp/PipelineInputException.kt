package com.osvin.aichallenge.pipeline.mcp

/**
 * Отказ по входу инструмента: аргумент не назван, назван недопустимо или разобрать его нечем.
 *
 * Исключением, а не значением, потому что причина одна на три инструмента и на все их ветки
 * проверки: тип превращает её в `isError` в одном месте (в теле инструмента), а сами проверки
 * бросают — иначе каждая из них возвращала бы результат, и «что вернуть» решалось бы в каждой
 * ветке заново. Наружу тип не выходит: клиент получает текст причины полем результата, как того
 * и требует протокол.
 *
 * @param message Что именно не так с вызовом — это уезжает модели словами.
 */
class PipelineInputException(message: String) : Exception(message)
