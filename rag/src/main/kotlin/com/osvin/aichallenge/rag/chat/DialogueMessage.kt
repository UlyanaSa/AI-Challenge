package com.osvin.aichallenge.rag.chat

import java.time.Instant

/**
 * Кто сказал реплику разговора.
 *
 * Роль — часть истории, а не подпись в отчёте: окно, которое уходит в промпт, собирается из реплик
 * по ролям, и «человек» против «ассистент» — это то, чем промпт объясняет модели, где чей текст.
 */
enum class DialogueRole(val title: String) {
    USER("человек"),
    ASSISTANT("ассистент")
}

/**
 * Реплика разговора: роль, текст и время — форма истории, которую называет задание дня.
 *
 * Задание описывает сообщение тремя полями (`role`, `content`, `timestamp`), и здесь они именно
 * такие, а не «вопрос с ответом в одном объекте»: у хода ([ChatTurn]) две реплики, и окно истории
 * собирается из них, а не из пар. Время у обеих реплик хода одно — момент, когда человек спросил:
 * своего времени у ответа модели никто не измеряет, а выдумать его значило бы показать в истории
 * точность, которой нет (полное время хода есть отдельно, [ChatTurn.totalMillis]).
 */
data class DialogueMessage(
    val role: DialogueRole,
    val content: String,
    val at: Instant
)
