package com.osvin.aichallenge.rag

/**
 * Факт, который должен быть в правильном ответе.
 *
 * Проверяется не дословный ответ, а наличие сведений: у факта есть слова-признаки, по которым
 * он засчитывается ([Check]). Признак — основа слова, а не слово целиком: ответ «тростью»
 * и ответ «трость» — про одно и то же, и требовать формулировку значило бы проверять слог, а не
 * знание.
 *
 * Признаков у факта несколько, и хватает любого: они перечисляют не «все слова», а «как это
 * называют». Сюда попадают формы, которыми одно и то же пишут по-разному: число «двадцать два»
 * в ответе легко становится «двадцати двух» или «22», а «два раза» — «дважды». Список форм ведётся
 * руками и остаётся неполным по построению: синоним, которого в нём нет, проверка не засчитает,
 * и это видно в отчёте как незасчитанный факт, а не как ошибка молча.
 */
data class Fact(
    /** Ожидание словами: попадает в отчёт, чтобы человек видел, что именно засчитано. */
    val text: String,
    /** Основы слов и словосочетания, по которым факт ищется в ответе. */
    val keywords: List<String>
)

/**
 * Контрольный вопрос набора: что спросили, что должно быть в ответе, где ответ лежит и чем
 * считается правильный ответ.
 *
 * У вопроса три описания ожидания, и они нужны разным читателям. [expected] — ответ словами: его
 * читает человек в отчёте, и по нему видно, чего ответ модели не сказал. [facts] — то же ожидание
 * в виде, который можно считать ([Check]): из него складывается оценка 0–2. [pages] и [section] —
 * место в базе: по ним видно, нашёл ли поиск то, что должен был найти, и опёрся ли ответ
 * на найденное. Вопрос без места в базе проверял бы одну память модели, и от режима с RAG
 * не осталось бы ничего, что можно предъявить.
 */
data class ControlQuestion(
    val id: String,
    val question: String,
    /** Правильный ответ словами: эталон для сравнения, в оценке не участвует. */
    val expected: String,
    val facts: List<Fact>,
    /** Страницы книги, где лежит ответ. Пусто у вопроса, ответа на который в базе нет. */
    val pages: List<Int>,
    /** Глава книги, где лежит ответ. */
    val section: String,
    /** Чем вопрос интересен сравнению — почему он в наборе. */
    val note: String
) {

    /**
     * Ответа в базе нет.
     *
     * Такой вопрос — проверка не памяти модели, а поведения режима с RAG: у него нет страниц
     * ([pages] пуст), потому что искать нечего, и правильным ответом считается не факт из книги,
     * а признание, что в найденных фрагментах этих сведений нет. В оценке поиска он поэтому
     * не участвует: считать «источник не найден» ошибкой там, где источника нет, значило бы
     * наказывать поиск за правильное поведение.
     */
    val absent: Boolean get() = pages.isEmpty()
}

