package com.osvin.aichallenge.rag

import com.osvin.aichallenge.agent.LlmClient
import com.osvin.aichallenge.models.DeepSeekRequest

/**
 * Отсечение слабых кандидатов по близости: `similarity >= threshold`.
 *
 * Порог — параметр прогона, а не константа кода, и это главное решение этого этапа. У косинуса нет
 * универсального «правильного» значения: шкала зависит от модели векторов и от однородности корпуса
 * (на одной книге близости сжаты), поэтому порог подбирается на своих вопросах и своём индексе —
 * подбор делает прогон ([RagCli]), а конвейер получает готовое число.
 *
 * Порог `0.0` означает «не отсекать»: близости неотрицательны, и строгое `>= 0.0` оставляет всех.
 * Так у эксперимента есть точка «фильтра нет», с которой сравниваются остальные, и нет второй ветки
 * кода «фильтр выключен».
 *
 * Отсекаются кандидаты, а не факты: чанк, в котором ответ есть, но который слабо похож на вопрос,
 * теряется — и это видно в отчёте отдельным счётчиком ошибочно отфильтрованных правильных чанков,
 * иначе высокая цена фильтра осталась бы незаметной.
 */
class SimilarityFilter(val threshold: Double) {

    /** Оставляет кандидатов не ниже порога, сохраняя порядок выдачи. */
    fun keep(candidates: List<Source>): List<Source> = candidates.filter { it.similarity >= threshold }

    /** Название этапа для отчёта: у порога нет имени, но есть число, которым он задан. */
    val name: String get() = if (threshold <= 0.0) "без порога" else "similarity >= ${"%.2f".format(threshold)}"
}

/** Кандидат с оценкой второго этапа: чем полезнее фрагмент вопросу, тем выше оценка. */
data class Scored(val source: Source, val score: Double)

/**
 * Что вернул второй этап: порядок, сколько кандидатов оценено моделью и чем закончился разбор.
 *
 * [scoredByModel] отдельно от размера списка, потому что у варианта с моделью оценка может не
 * разобраться, и тогда кандидат остаётся с близостью вместо оценки. Без этого числа сбой формата
 * выглядел бы как обычный порядок, и «реранкер переставил фрагменты» было бы неправдой.
 *
 * По умолчанию это ноль, а не размер списка: считать моделью оценки того, кто к ней не обращался,
 * нельзя. Первый прогон дня 23 показывал на эвристическом втором этапе «оценено моделью 3 из 3» —
 * строка в отчёте была ложной, потому что умолчание было взято от длины списка. Число оценивает
 * модель и только она, поэтому заполняет его вариант с моделью.
 */
data class Rerank(
    val scored: List<Scored>,
    val scoredByModel: Int = 0,
    val note: String? = null
)

/**
 * Второй этап оценки релевантности: порядок кандидатов по смыслу, а не по близости векторов.
 *
 * Контракт отдельный, потому что задание перечисляет несколько допустимых вариантов (модель,
 * оценка по признакам, их комбинация) и требует менять алгоритм, не трогая конвейер. Всё, что
 * конвейер знает про этап: он получает вопрос и кандидатов, а возвращает тот же список с оценками.
 *
 * Вопрос приходит исходный, а не переписанный: полезность фрагмента определяется тем, отвечает ли
 * он на вопрос человека, а переписанный запрос — это уже средство поиска, а не то, на что нужен
 * ответ.
 */
interface Reranker {

    /** Как называется вариант в отчёте: по этому имени числа прогонов различимы. */
    val name: String

    suspend fun rank(question: String, candidates: List<Source>): Rerank
}

/**
 * Эвристический реранкер: покрытие значимых слов вопроса, имена собственные и близость.
 *
 * Решение, которое здесь принимается: второй этап не обязан быть моделью. У вопроса из набора есть
 * имена и числа, и они решают больше, чем общая близость, — фрагмент, где нет ни одного значимого
 * слова вопроса, но который близок по вектору (таков q10: близости 0,45–0,51 у фрагментов про отца,
 * а не про сына), по этим признакам падает вниз без обращения к модели, то есть бесплатно
 * и воспроизводимо.
 *
 * Оценка — взвешенная сумма трёх чисел, каждое в диапазоне 0…1:
 *
 * - **покрытие** (вес 0.5) — доля уникальных значимых слов вопроса (без служебных), найденных
 *   в чанке; сравнение идёт по началу словоформы ([Check.matches]) от основы в пять букв, поэтому
 *   «Лебедкиным» в вопросе и «Лебедкина» в тексте — одно слово, а не два разных;
 * - **имена собственные** (вес 0.4) — доля слов вопроса, написанных с заглавной буквы (кроме
 *   начального), найденных в чанке: в вопросах набора это как раз те слова, которые указывают
 *   на нужный эпизод;
 * - **близость** (вес 0.1) — её вес намеренно мал: она уже сделала свою работу в поиске, и если
 *   реранкер повторит её с большим весом, второго этапа не будет вовсе.
 *
 * Веса — это утверждение о том, что важнее, и оно проверяемо: альтернатива ([LlmReranker]) считается
 * на тех же кандидатах, и отчёт показывает, изменился ли порядок и попал ли ответ в контекст.
 */
class HeuristicReranker : Reranker {

    override val name: String = "эвристика (слова, имена, близость)"

    override suspend fun rank(question: String, candidates: List<Source>): Rerank {
        val words = significant(question)
        val names = properNames(question)

        val scored = candidates.map { source ->
            val text = Check.normalize(source.text)
            val coverage = shareOf(words) { word -> Check.matches(text, word) }
            val named = shareOf(names) { name -> Check.matches(text, name) }
            Scored(source, COVERAGE_WEIGHT * coverage + NAMES_WEIGHT * named + SIMILARITY_WEIGHT * source.similarity)
        }
        return Rerank(scored)
    }


    /** Доля найденных слов; пустой список даёт ноль, а не единицу: признака нет — вклада нет. */
    private fun shareOf(words: List<String>, found: (String) -> Boolean): Double =
        if (words.isEmpty()) 0.0 else words.count(found).toDouble() / words.size

    companion object {

        const val COVERAGE_WEIGHT = 0.5
        const val NAMES_WEIGHT = 0.4
        const val SIMILARITY_WEIGHT = 0.1

        /** Длина основы: см. [stem]. */
        const val STEM_LENGTH = 5

        /**
         * Основа слова: первые пять букв (или слово целиком, если оно короче).
         *
         * Сравнивать слова вопроса с текстом целиком нельзя: в вопросе «Лебедкиным», в книге
         * «Лебедкина», и по полному слову это два разных слова — покрытие обнулилось бы на самом
         * важном слове. Взять основу морфологически нечем (стеммера в проекте нет), поэтому берётся
         * грубая основа по длине: пять букв покрывают падежи имён и терминов этого набора
         * («Шатов»/«Шатову», «Виргинский»/«Виргинского», «Липутин»/«Липутина»), а более длинная
         * основа начала бы терять формы («шатову» при шести буквах уже не совпадёт с «Шатов»).
         */
        fun stem(word: String): String = word.take(minOf(STEM_LENGTH, word.length))

        /**
         * Значимые слова вопроса: без служебных и коротких.
         *
         * Список служебных слов перечислен, а не взят из библиотеки: он нужен одному признаку
         * и должен читаться в коде — «почему» и «сколько» есть почти в любом вопросе набора, и без
         * отсечения покрытие мерило бы совпадение вопросительных слов. Короткие слова (до трёх букв)
         * отсеиваются отдельно: среди них почти нет значимых, зато есть предлоги, которых нет
         * в списке.
         */
        val STOP = setOf(
            "что", "кто", "как", "какой", "какая", "какое", "какие", "чем", "кем", "кому", "чему",
            "где", "когда", "почему", "зачем", "сколько", "который", "которая", "это", "этот",
            "был", "была", "было", "были", "есть", "быть", "или", "если", "чтобы", "него", "нему",
            "них", "ним", "ней", "его", "её", "ее", "их", "себя", "свой", "своей", "весь", "всё",
            "все", "сам", "сама", "такой", "также", "тоже", "тогда", "там", "тут", "этом", "того"
        )

        fun significant(question: String): List<String> = words(question)
            .filter { it.length >= 4 && it !in STOP }
            .map { stem(it) }

        /**
         * Имена собственные вопроса: слова с заглавной буквы, кроме первого — оно с заглавной
         * по правилу начала предложения, и в вопросе «Что Виргинский сделал…» первым стоит «Что».
         */
        fun properNames(question: String): List<String> = question
            .split(' ')
            .drop(1)
            .map { it.trim().trim(',', '.', '?', '!', ':', ';') }
            .filter { it.length >= 3 && it.first().isUpperCase() }
            .map { stem(it) }

        /** Слова в нормализованном виде: та же нормализация, что у проверки фактов. */
        fun words(text: String): List<String> = Check.normalize(text)
            .split(' ')
            .filter { it.isNotEmpty() }
            .distinct()
    }
}

/**
 * Реранкер на модели: оценка 0–10 каждому кандидату одним запросом.
 *
 * Один запрос на вопрос, а не по запросу на фрагмент: кандидатов десять, и оценки имеют смысл
 * только друг относительно друга — при отдельном запросе каждая оценка ставилась бы без остальных
 * на глазах, и «8» в одном запросе ничего не значило бы рядом с «8» в другом.
 *
 * Разбор ответа прощает сбой формата, но не молчит о нём: кандидат без разобранной оценки остаётся
 * с близостью в роли оценки (порядок при этом сохраняется по ней), а [Rerank.scoredByModel] и
 * [Rerank.note] говорят, что именно произошло. Так прогон с неразобравшимся ответом видно
 * в отчёте, а не приходится догадываться, почему порядок совпал с выдачей поиска.
 */
class LlmReranker(
    private val llm: LlmClient,
    private val model: String,
    private val maxTokens: Int = RERANK_BUDGET,
    private val temperature: Double = 0.0
) : Reranker {

    override val name: String = "модель $model (без рассуждения)"

    override suspend fun rank(question: String, candidates: List<Source>): Rerank {
        if (candidates.isEmpty()) return Rerank(emptyList(), scoredByModel = 0)

        val response = llm.complete(
            DeepSeekRequest(
                model = model,
                messages = Prompt.rerank(question, candidates),
                maxTokens = maxTokens,
                temperature = temperature,
                reasoningEffort = REASONING_EFFORT
            )
        )
        val answer = response.choices.firstOrNull()?.message?.content.orEmpty()
        val parsed = parse(answer, candidates)

        val scored = candidates.map { source ->
            val score = parsed.scores[source.rank]
            Scored(source, score ?: source.similarity)
        }
        return Rerank(
            scored = scored,
            scoredByModel = parsed.scores.size,
            note = parsed.note
        )
    }

    /**
     * Разбор ответа: пары «номер=оценка», а если номеров нет — список оценок по порядку фрагментов.
     *
     * Второй формат пришлось принять по замеру: модель отвечает то парами, то голыми числами по
     * строке на фрагмент («5», «5», «0», «0», …). Отказаться от такого ответа значило бы выбросить
     * готовые оценки из-за отсутствия подписи — а номера в запросе проставлены, и порядок строк
     * в ответе тот же, что порядок фрагментов. Список принимается, только когда чисел ровно столько
     * же, сколько кандидатов: при другом количестве неизвестно, какое число к какому фрагменту
     * относится, и тогда кандидаты остаются с близостью.
     *
     * Про разбор сказано в замечании этапа ([Rerank.note]), включая ответ модели: без этого
     * неразобранный ответ неотличим от полного провала, и «второй этап ничего не изменил» читалось бы
     * как его свойство, а не как сбой формата. Первый прогон дня 23 так и прошёл: оценки разобрались
     * у одного кандидата из десяти, в отчёте было видно число, а что ответила модель — нет.
     */
    private fun parse(answer: String, candidates: List<Source>): Parsed {
        val pairs = SCORES.findAll(answer)
            .mapNotNull { match ->
                val rank = match.groupValues[1].toIntOrNull()
                val score = match.groupValues[2].replace(',', '.').toDoubleOrNull()
                if (rank == null || score == null) null else rank to score
            }
            .toMap()
        if (pairs.size == candidates.size) return Parsed(pairs, note = null)

        val list = answer.lines().map { it.trim() }.filter { it.isNotEmpty() }
        val numbers = list.mapNotNull { NUMBER.matchEntire(it)?.groupValues?.get(1)?.replace(',', '.')?.toDoubleOrNull() }
        if (numbers.size == candidates.size) {
            return Parsed(
                scores = candidates.mapIndexed { index, source -> source.rank to numbers[index] }.toMap(),
                note = "модель ответила списком оценок по порядку фрагментов, без номеров"
            )
        }

        val spent = pairs.size
        return Parsed(
            scores = pairs,
            note = when {
                spent == 0 -> "оценки модели не разобраны: порядок по близости. Ответ модели: ${answer.trim().take(RAW_LIMIT)}"
                else -> "оценки модели разобраны у $spent из ${candidates.size} кандидатов, остальные — по близости. " +
                    "Ответ модели: ${answer.trim().take(RAW_LIMIT)}"
            }
        )
    }

    /** Что вышло из разбора ответа: оценки по номерам фрагментов и замечание, если что-то не так. */
    private data class Parsed(val scores: Map<Int, Double>, val note: String?)

    private companion object {

        /**
         * Бюджет ответа: одна строка на кандидата.
         *
         * Значение исправлено после первого прогона дня 23 вместе с режимом рассуждения. Модель
         * рассуждающая, её мысли идут отдельным полем, но тратят тот же бюджет завершения: с бюджетом
         * в 1024 токена ответ на пяти вопросах из десяти приходил пустым, разбор не находил ни одной
         * строки, и второй этап молча откатывался к близости. Рассуждение этому этапу не нужно —
         * оценка «полезен / не полезен» не требует вывода, — поэтому запрос идёт в режиме без
         * рассуждения, а бюджет сокращён до 512 токенов: на замер десяти кандидатов ушло 39 токенов.
         */
        const val RERANK_BUDGET = 512

        /** Режим без рассуждения: см. [RERANK_BUDGET]. */
        const val REASONING_EFFORT = "none"

        /** Сколько символов ответа модели попадает в замечание этапа. */
        const val RAW_LIMIT = 300

        /**
         * Строка оценки: «номер=оценка» с любыми пробелами вокруг знака.
         *
         * Оценка допускает десятичную дробь и запятую: модель пишет «7.5» и «7,5» одинаково охотно,
         * а разница между ними для порядка — ничто. Разделитель принимается и «=», и «:», потому что
         * оба встречаются в ответах на просьбу «номер=оценка».
         */
        val SCORES = Regex("(\\d+)\\s*[=:]\\s*(\\d+(?:[.,]\\d+)?)")

        /** Строка списка: одно число и ничего больше — так модель отвечает, когда номера не пишет. */
        val NUMBER = Regex("(\\d+(?:[.,]\\d+)?)")
    }
}
