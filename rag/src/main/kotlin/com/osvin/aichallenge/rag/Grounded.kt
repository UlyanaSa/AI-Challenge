package com.osvin.aichallenge.rag

import com.osvin.aichallenge.models.ChatMessage

/**
 * Утверждение ответа вместе с цитатой из фрагмента, который его подтверждает.
 *
 * Разделение на утверждение и цитату — суть дня: ответ модели пересказывает, а цитата обязана быть
 * куском исходного текста ([Citations] проверяет это по тексту чанка), и связь между ними видна
 * читателю. [fragment] — номер фрагмента в контексте: только по нему система находит, из какого
 * чанка взята цитата, и модель не может назвать источник, которого ей не давали.
 */
data class Claim(
    /** Утверждение так, как его сформулировала модель. */
    val text: String,
    /** Номер фрагмента в контексте: 1 — первый из переданных, а не место в векторной выдаче. */
    val fragment: Int,
    /** Цитата из этого фрагмента: должна быть его текстом, а не пересказом. */
    val quote: String
)

/**
 * Источник в том виде, в каком он уходит пользователю: собран системой из метаданных чанка.
 *
 * Это прямое требование задания (§4): источник формируется из метаданных, а не генерируется моделью.
 * Отсюда и устройство типа — здесь нет ни одного поля, которое взялось бы из ответа модели: [source],
 * [section], [chunkId], [chunkIndex] и [pages] приходят из чанка, найденного поиском, [similarity] —
 * из векторной близости, [rerankScore] — из второго этапа. Модель называет только номер фрагмента,
 * и по нему система достаёт готовую запись; придумать страницу или раздел она не может, потому что
 * их в её ответе просто нет.
 *
 * [rank] — тот же номер, что был у фрагмента в контексте: по нему цитаты связываются с источником,
 * и в отчёте источники идут в том порядке, в каком их видела модель.
 */
data class SourceRef(
    val rank: Int,
    /**
     * Номер фрагмента в контексте, на который ссылается утверждение: «[N]» из ответа модели.
     *
     * Нужен пользователю, чтобы связать цитату с источником: цитаты нумеруются номерами фрагментов,
     * и без этого номера рядом с источником связь пришлось бы искать глазами по названию главы.
     */
    val fragment: Int,
    /** Файл корпуса: «book.md». */
    val source: String,
    /** Раздел книги (глава), если он есть у чанка. */
    val section: String?,
    /** Идентификатор чанка в индексе — то, что задание называет `chunk_id`. */
    val chunkId: String,
    /** Номер чанка в индексе: по нему чанк находится в файле индекса и в отчёте дня 23. */
    val chunkIndex: Int,
    val pages: List<Int>,
    val title: String?,
    /** Близость вектора вопроса и вектора чанка. */
    val similarity: Double,
    /** Оценка второго этапа; `null`, если этапа не было или кандидат оценён не был. */
    val rerankScore: Double?
) {

    /**
     * Строка источника для отчёта: то, что задание просит показать пользователю (§3).
     *
     * `chunk_id` — идентификатор чанка из индекса (`structural:book/book.md#7`), а не его номер
     * в выдаче: номер меняется от вопроса к вопросу, а идентификатор указывает на конкретный
     * фрагмент текста, и проверить ответ можно только по нему. Номер фрагмента в контексте
     * ([fragment]) печатается отдельно — он связывает источник с цитатой.
     */
    val label: String = buildString {
        append("source: ").append(source)
        section?.let { append(" · section: ").append(it) }
        append(" · chunk_id: ").append(chunkId)
        append(" · фрагмент [").append(fragment).append("]")
    }

    companion object {

        /**
         * Источник для отчёта: метаданные чанка и оценки этапов.
         *
         * [candidate] передаётся, чтобы рядом с близостью стояла оценка второго этапа: без неё
         * не видно, почему фрагмент оказался в контексте — по близости или потому, что его поднял
         * реранкер. Пустая оценка означает «второй этап его не оценивал», а не «оценил в ноль».
         */
        fun of(source: Source, fragment: Int, candidate: Candidate? = null): SourceRef = SourceRef(
            rank = source.rank,
            fragment = fragment,
            source = source.source,
            section = source.section,
            chunkId = source.id,
            chunkIndex = source.chunkIndex,
            pages = source.pages,
            title = source.title,
            similarity = source.similarity,
            rerankScore = candidate?.rerankScore
        )
    }
}

/**
 * Результат программной проверки одной цитаты (§11 задания).
 *
 * Проверка не доверяет модели: цитата ищется в тексте того чанка, на который модель сослалась,
 * и [found] выставляется по тексту, а не по обещанию. [reason] объясняет отказ, потому что причин
 * у невалидной цитаты несколько и лечатся они по-разному: цитата не из контекста — это выдуманный
 * источник, цитата не найдена в чанке — пересказ, выданный за цитату, слишком короткая цитата —
 * не подтверждение вовсе.
 *
 * [chunkId] пуст, когда цитату не с чем сверять: модель сослалась на номер, которого в контексте
 * не было. Такой случай — не «нет данных для проверки», а провал проверки, и он считается
 * наравне с остальными.
 */
data class QuoteCheck(
    val claim: Claim,
    val chunkId: String?,
    val found: Boolean,
    val reason: String?
)

/**
 * Достаточность контекста перед обращением к модели (§8, §9 задания).
 *
 * Четыре состояния, а не «хватит / не хватит»: причины отказа разные, и счёт по ним показывает,
 * что именно сломалось. Пустая выдача — плохой поиск или его отсутствие, все кандидаты отсеяны —
 * порог фильтра, лучший фрагмент ниже порога достаточности — расхождение между порогом фильтра
 * и порогом уверенности (фильтр может быть выключен или стоять ниже).
 */
enum class Confidence(val title: String) {

    /** Контекст есть и он не ниже порога: можно спрашивать модель. */
    SUFFICIENT("контекст достаточен"),

    /** Поиск не вернул ни одного фрагмента — спрашивать не о чем. */
    NO_CHUNKS("поиск не нашёл ни одного фрагмента"),

    /** Фрагменты были, но порог фильтра убрал все. */
    ALL_FILTERED("все найденные фрагменты отсеяны порогом"),

    /** В контексте что-то осталось, но лучший фрагмент ниже порога достаточности. */
    BELOW_THRESHOLD("лучший фрагмент ниже порога достаточности")
}

/**
 * Решение о достаточности контекста вместе с числами, по которым оно принято.
 *
 * [bestSimilarity] — близость лучшего фрагмента **из тех, что дошли до контекста**: уверенность
 * считается по тому, что увидит модель, а не по тому, что нашлось. Пустое значение — не ноль,
 * а его отсутствие: в контексте никого нет, и сравнивать не с чем.
 */
data class ConfidenceCheck(
    val decision: Confidence,
    /** Сколько кандидатов дошло до контекста. */
    val considered: Int,
    val bestSimilarity: Double?,
    val threshold: Double
) {

    val sufficient: Boolean get() = decision == Confidence.SUFFICIENT
}

/**
 * Почему система отказалась отвечать.
 *
 * Два отказа, и они из разных половин дня. [NO_CONTEXT] ставит проверка достаточности **до** модели:
 * контекст слаб, и модели не задаётся вопрос — иначе она ответила бы по памяти. [NO_EVIDENCE] ставит
 * проверка цитат **после** модели: контекст был, но ни одно утверждение не подтвердилось найденным
 * текстом (модель сказала, что ответа нет, или привела цитаты, которых в чанках не оказалось).
 * Разница видна в логе: в первом случае обращения к модели не было вовсе.
 */
enum class Refusal(val title: String) {

    /** Контекст недостаточен: модель не спрашивали (§8, §10). */
    NO_CONTEXT("контекст недостаточен"),

    /** Модель не подтвердила ни одного утверждения цитатами (§11). */
    NO_EVIDENCE("ни одно утверждение не подтверждено цитатой")
}

/**
 * Ответ grounded-режима: либо подтверждённый ответ с источниками и цитатами, либо отказ.
 *
 * Тип нарочно не даёт собрать ответ «вполовину»: [sources] и [claims] заполняются только у ответа,
 * а у отказа они пусты, потому что задание запрещает добавлять источники ради выполнения требования
 * о наличии цитат (§10). Если бы отказ мог нести список источников, соблазн «показать хоть что-то»
 * рано или поздно победил бы, и отказ перестал бы быть честным.
 *
 * [checks] — результат программной проверки каждой цитаты, включая отброшенные: по нему видно,
 * что именно модель выдумала. [raw] — ответ модели как он есть: без него непонятно, отказалась
 * модель сама или система отбросила её цитаты. [messages] и [retrieval] хранятся ради лога (§19):
 * контекст, ушедший в модель, задним числом не восстановить.
 */
data class GroundedAnswer(
    val question: String,
    /** Вся выдача поиска с этапами: по ней считается и достаточность, и проверки источников. */
    val retrieval: Retrieval,
    val confidence: ConfidenceCheck,
    /** Текст ответа модели; пусто у отказа. */
    val answer: String?,
    /** Источники, собранные системой из метаданных процитированных чанков. */
    val sources: List<SourceRef>,
    /** Утверждения с подтверждёнными цитатами: неподтверждённые сюда не попадают. */
    val claims: List<Claim>,
    /** Проверка **всех** цитат ответа, включая отброшенные. */
    val checks: List<QuoteCheck>,
    val refusal: Refusal?,
    /** Запрос к модели; пуст, если до модели дело не дошло. */
    val messages: List<ChatMessage>,
    /** Сырой ответ модели: нужен логу, чтобы разбирать сбои формата. */
    val raw: String?,
    val promptTokens: Int?,
    val completionTokens: Int?,
    val finishReason: String?,
    val millis: Long,
    /**
     * Что пошло не так на проверках: причина отказа, отброшенные цитаты, решение достаточности.
     *
     * Ровно тот же аргумент, что у [Trace.note]: без строки-объяснения «цитат нет» неотличимо
     * от «модель ответила не тем форматом», а это разные поломки с разными лекарствами. В лог
     * замечание попадает вместе с сырым ответом модели, и разбирать прогон можно, не повторяя его.
     */
    val note: String? = null
) {

    val refused: Boolean get() = refusal != null

    /**
     * Ответ подтверждён цитатами: он есть, отброшенных цитат нет, и каждое утверждение опирается
     * на проверенную цитату.
     *
     * Проверка «нет отброшенных» намеренно строгая. Ответ, у которого половина утверждений
     * подтверждена, а половина — пересказ без цитаты, читается как подтверждённый целиком, и именно
     * так выглядит галлюцинация, прошедшая проверку. Доля подтверждённых ответов считается отдельно
     * ([GroundingSummary.grounded]), а это поле отвечает на вопрос «подтверждён ли ответ полностью».
     */
    val grounded: Boolean
        get() = !refused && claims.isNotEmpty() && checks.all { it.found } && answer != null

    companion object {

        /**
         * Текст отказа, который видит пользователь.
         *
         * Формулировка из задания (§8) дословно: она говорит и то, что ответа нет, и что делать
         * дальше — уточнить вопрос. Второе важнее первого: отказ без просьбы уточнить читался бы
         * как «система сломалась», а не как «в базе этого нет».
         */
        const val REFUSAL_TEXT: String =
            "Я не знаю ответа на основании доступных источников. Уточните вопрос или предоставьте " +
                "дополнительный контекст."
    }
}
