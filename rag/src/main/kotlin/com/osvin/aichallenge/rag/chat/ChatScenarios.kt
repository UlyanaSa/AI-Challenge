/**
 * Шаг сценария: реплика человека и то, что на неё обязано быть в ответе.
 *
 * Проверка сценария делится на две части, и это решение, а не удобство. **Поведение** ([kind],
 * [refusal], [goal]) — ожидания того, как система отвечает на такой-то ход: вопрос о книге — по базе
 * с источником, вопрос о разговоре — по памяти задачи, где базы не хватает — отказ. **Сведения**
 * ([facts]) — что именно назвал ответ, и сверяются они теми же фактами дня 22 ([Fact], `Check`):
 * сколько названо, столько и названо. Обе части измеряются и печатаются, но приговор дня
 * ([ChatScenarioRun.accepted]) решают требования задания, а не эти ожидания: почему один отказ там,
 * где в другом прогоне был ответ, не делает день несданным — объяснено в [ChatScenarioRun].
 * Смешать части тоже нельзя: докладывать только «поведение в порядке» значило бы не говорить,
 * верны ли ответы, поэтому факты считаются отдельной строкой.
 *
 * [goal] отмечает шаги, где человек спрашивает о самом разговоре: ответ обязан назвать цель и
 * правила словами сценария ([ChatScenario.goalKeywords]), а не словами памяти. Память сформулирована
 * моделью, и проверять её ею же — значит проверять, что модель согласна сама с собой; слова сценария
 * написаны человеком и от модели не зависят. Исключение одно — [goalFromMemory]: у хода, который цель
 * ставит, ответа может не быть вовсе, и тогда цель сверяется с памятью (почему — при самом признаке).
 */
data class ChatScenarioStep(
    val text: String,
    /** Ожидаемые сведения ответа: проверяются по тексту ответа, как в дне 22. */
    val facts: List<Fact> = emptyList(),
    /** Ожидаемый вид ответа; `null` — вид не важен, годится и отказ. */
    val kind: ChatAnswerKind? = null,
    /** Ответ обязан назвать цель разговора словами сценария. */
    val goal: Boolean = false,
    /** Ответа в базе нет: ожидается отказ, а не выдумка. */
    val refusal: Boolean = false,
    /** Что этим шагом проверяется — для отчёта и для того, кто будет читать сценарий. */
    val note: String? = null,
    /**
     * Цель проверяется не по ответу, а по памяти задачи после этого хода.
     *
     * Это признак шага, который цель **ставит**: первый ход разговора. Ответ на постановку цели
     * не несёт утверждений о книге, и модель отвечает на него по-разному — то подтверждением
     * разговора, то первым ответом по базе, — а иногда её JSON обрывается, и честный разбор даёт
     * отказ (живой прогон дал и то, и другое, и третье). Требовать от этого хода именно ответа
     * значило бы объявлять день непринятым из-за формата ответа на реплику, которая ничего
     * не спрашивает. Проверяется здесь то, ради чего шаг и существует: цель разговора попала
     * в память задачи на этом же ходу и сформулирована теми же словами, что у человека.
     */
    val goalFromMemory: Boolean = false
)

/**
 * Сценарий разговора: набор реплик, у которого есть цель и проверяемые ожидания.
 *
 * Сценарии живут в коде, а не в файле рядом, по той же причине, что и набор вопросов дня 22
 * (`Controls`): их прогоняют тесты и проверки, а ожидания — это код (факты, виды ответа, слова
 * цели), а не текст для чтения. Из этого следует и то, что сценарий воспроизводим: он не зависит
 * от того, что человек напечатает в чате, — и то, что он проверяем: его можно прогнать дважды
 * и сравнить числа.
 *
 * [goalKeywords] пишутся человеком и описывают цель так, как её назвал бы он сам: по ним видно,
 * что ответ на «что мы разбираем» говорит о том же разговоре, а не о посторонней теме. Проверять
 * по формулировке памяти было бы проверкой модели моделью.
 */
data class ChatScenario(
    /** Имя для запуска, файлов и адресов: `scene-1`. */
    val name: String,
    /** Заголовок для отчёта. */
    val title: String,
    /** Цель разговора так, как её ставит человек в первой реплике. */
    val goal: String,
    /** Слова, по которым видно, что ответ называет именно эту цель. */
    val goalKeywords: List<String>,
    /**
     * Сколько ограничений сценарий устанавливает.
     *
     * Проверяется не «память выросла», а «названное человеком не потерялось»: слияние памяти
     * ([TaskMemory.merge]) устроено так, что потерять записанное нельзя, — значит, эта проверка
     * ловит не слияние, а извлечение: если модель не разобрала ограничение, его не будет вовсе.
     */
    val expectedConstraints: Int,
    /** Сколько терминов сценарий закрепляет; проверка та же, что у ограничений. */
    val expectedTerms: Int,
    /** Реплики человека по порядку. */
    val steps: List<ChatScenarioStep>
) {

    /** Сколько реплик в сценарии: длинным считается разговор, где реплик заметно больше десяти. */
    val length: Int get() = steps.size
}

