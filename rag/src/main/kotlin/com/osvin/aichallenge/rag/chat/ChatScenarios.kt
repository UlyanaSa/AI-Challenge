 *    сценария), а память задачи — записать цель. Вид ответа на первой реплике не задан намеренно:
 *    живой прогон показал, что модель отвечает на такую реплику по-разному — и подтверждением
 *    разговора, и первым ответом по базе (в постановке цели есть вопрос, замаскированный под план:
 *    «кем был Степан Трофимович»). Требовать один вид значило бы проверять форму, а не то, что цель
 *    понята и записана. Настоящая проверка «цель держится» стоит не здесь, а в репликах «напомни,
 *    что мы разбираем» — в середине и в конце разговора: там ответ обязан вернуться к цели после
 *    десятка шагов, и именно этого требует задание дня.
