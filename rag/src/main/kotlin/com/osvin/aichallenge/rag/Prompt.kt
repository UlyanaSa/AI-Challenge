package com.osvin.aichallenge.rag

import com.osvin.aichallenge.models.ChatMessage

/**
 * Запрос к модели в двух режимах: с найденными фрагментами базы и без них.
 *
 * Разница между режимами — ровно то, что добавляет RAG: блок фрагментов и правило опираться
 * на них. Всё остальное обязано совпадать дословно — название книги, требование краткости
 * и текст вопроса, — иначе сравнение мерило бы разницу промптов, а не пользу поиска. Поэтому
 * одинаковые части лежат здесь одной константой ([TASK] и [QUESTION_PREFIX]), и оба режима берут
 * их из неё: правка в одном месте не может разойтись с другим.
 *
 * В режиме без RAG поиск не выполняется, поэтому фрагментов нет и в запросе: модель отвечает
 * тем, что помнит о книге. Это и есть предмет сравнения — память модели против её же чтения
 * найденного текста.
 *
 * Фрагменты уходят целиком, а не выжимкой ([AnswerFragment] со страницы дня 21 здесь не нужен):
 * выжимка выбирает предложения по словам вопроса, и в неё может не попасть ответ, который в чанке
 * есть. Резать контекст ради экономии токенов здесь нечего: три фрагмента задания занимают около
 * двух с половиной тысяч токенов при бюджете ответа, который задаёт прогон.
 */
object Prompt {

    /** Общая часть обоих системных сообщений: без неё сравнение перестало бы быть сравнением. */
    const val TASK: String = "Ты отвечаешь на вопрос по роману Ф. М. Достоевского «Бесы». " +
        "Отвечай кратко: три–пять предложений, своими словами."

    /** Начало вопроса в пользовательском сообщении: одно и то же в обоих режимах. */
    const val QUESTION_PREFIX: String = "Вопрос: "

    /**
     * Системное сообщение режима с RAG: то же задание плюс правила работы с фрагментами.
     *
     * Правило «если ответа во фрагментах нет — сказать об этом» важнее двух остальных: без него
     * модель дописывает ответ по памяти, и режим с RAG перестаёт отличаться от режима без RAG,
     * а сравнение теряет смысл. Номера фрагментов и страницы нужны отчёту: по ним видно, на какой
     * источник модель оперлась, и это отдельная проверка набора ([Controls]).
     */
    val SYSTEM_WITH_CONTEXT: String = TASK + "\nНиже даны фрагменты книги, найденные по этому вопросу.\n" +
        "Правила:\n" +
        "1. Опирайся только на фрагменты и не дополняй их тем, что помнишь о романе. Если во фрагментах\n" +
        "ответа нет, скажи об этом прямо и не додумывай.\n" +
        "2. Назови номера фрагментов, на которые ты опирался, и страницы.\n" +
        "3. Не пересказывай фрагменты целиком — ответь на вопрос."

    /** Системное сообщение режима без RAG: то же задание, фрагментов не будет. */
    val SYSTEM_WITHOUT_CONTEXT: String = TASK

    /**
     * Системное сообщение Query Rewrite: из вопроса — запрос для поиска по книге.
     *
     * Требования задания переписаны здесь как правила, потому что каждое из них проверяется после
     * прогона: смысл вопроса должен сохраниться (иначе сравнение мерило бы другой вопрос), факты
     * и имена нельзя придумывать (проверка ловит сущность, которой нет ни в вопросе, ни в книге),
     * местоимения и неоднозначные обращения нужно раскрыть (иначе поиск не знает, о ком речь),
     * а имена, названия и термины — сохранить (по ним и находится чанк с ответом).
     *
     * Просится одна строка, а не абзац: запрос идёт в embedding, и развёрнутое пояснение в нём
     * размыло бы вектор вопроса так же, как лишние слова в самом вопросе. Формат ответа —
     * ключевые слова и словосочетания, потому что пример задания устроен именно так.
     */
    val REWRITE_SYSTEM: String = "Ты готовишь поисковый запрос к роману Ф. М. Достоевского «Бесы». " +
        "По вопросу читателя составь запрос, по которому в тексте романа найдётся место с ответом.\n" +
        "Правила:\n" +
        "1. Сохрани смысл вопроса; запрос — про то же самое, а не про похожее.\n" +
        "2. Не выдумывай сюжетных фактов и не добавляй имён, которых в романе нет. Дополнить можно\n" +
        "только то, что подразумевает сам вопрос: назвать героя полным именем, раскрыть местоимение,\n" +
        "заменить описательное выражение именем.\n" +
        "3. Сохрани значимые имена, названия и термины из вопроса — по ним и ищется фрагмент.\n" +
        "4. Ответь одной строкой: только запрос, ключевыми словами и словосочетаниями, без пояснений\n" +
        "и без знаков вопроса."

    /**
     * Системное сообщение reranker'а: насколько фрагмент полезен для ответа на вопрос.
     *
     * Оценка просится числом на фрагмент, а не готовым порядком: числа переживают сбой формата
     * (нераспознанный фрагмент получает близость вместо оценки), а перемешанный список — нет.
     * Шкала 0–10 нарочно с запасом к десяти кандидатам: по ней видно не только порядок, но и то,
     * что реранкер счёл фрагмент бесполезным.
     */
    val RERANK_SYSTEM: String = "Ты оцениваешь, насколько фрагмент романа Ф. М. Достоевского «Бесы» " +
        "полезен для ответа на вопрос читателя.\n" +
        "Поставь каждому фрагменту оценку от 0 до 10: 10 — в нём есть ответ на вопрос, 5 — он про то же " +
        "лицо или событие, но ответа в нём нет, 0 — он не по теме.\n" +
        "Отвечай строками вида «номер=оценка», по одной на каждый фрагмент, без пояснений. " +
        "Пример: 1=7, 2=2, 3=0 — то есть «1=7», «2=2», «3=0» в отдельных строках."

    /** Сообщения Query Rewrite: правило и сам вопрос, который переписывается. */
    fun rewrite(question: String): List<ChatMessage> = listOf(
        ChatMessage(role = SYSTEM, content = REWRITE_SYSTEM),
        ChatMessage(role = USER, content = "Вопрос: $question")
    )

    /**
     * Сообщения reranker'а: вопрос и пронумерованные кандидаты с местом в книге.
     *
     * Номер кандидата — то же число, которым он оценён в ответе модели, и по нему оценка связывается
     * с чанком. Метаданные (страницы, глава) даны рядом с текстом: глава и страница часто и говорят
     * реранкеру, что фрагмент не про тот эпизод.
     */
    fun rerank(question: String, candidates: List<Source>): List<ChatMessage> = listOf(
        ChatMessage(role = SYSTEM, content = RERANK_SYSTEM),
        ChatMessage(
            role = USER,
            content = buildString {
                appendLine("Вопрос: $question")
                appendLine()
                for (candidate in candidates) {
                    appendLine("[${candidate.rank}] ${candidate.label}")
                    appendLine(candidate.text)
                    appendLine()
                }
            }.trimEnd()
        )
    )

    /**
     * Системное сообщение grounded-режима: ответ, который можно проверить по тексту.
     *
     * Отличие от [SYSTEM_WITH_CONTEXT] принципиальное, и оно не в строгости формулировок, а в том,
     * что здесь требуется **доказательство**. День 22 просил «опирайся на фрагменты» и получал ответ,
     * который фрагментами объяснялся, но не подтверждался: проверить, что утверждение взято
     * из найденного текста, было нечем. Здесь у каждого утверждения есть цитата, и она обязана быть
     * куском чанка дословно ([Citations]) — пересказ не засчитывается, и это сказано модели прямо,
     * потому что пересказ в кавычках — самая правдоподобная форма галлюцинации.
     *
     * Про источник сказано отдельно и в одну сторону: модель называет **только номер фрагмента**,
     * а страницы, главу и идентификатор подставляет система из метаданных (§4). Если бы модель
     * называла страницу сама, придуманная страница была бы неотличима от настоящей — она выглядела бы
     * так же, и проверить её было бы не с чем сверить. Формат просится JSON-объектом: разбор
     * ошибается на вольном тексте, а непонятный ответ система считает отказом.
     *
     * Правило «если ответа нет — сказать об этом» здесь сильнее, чем в дне 22: там отказ был
     * правильным поведением, а здесь он ещё и обязателен как поле `insufficient`. Модель,
     * которая «на всякий случай» ответит по памяти, роняет проверку цитат — и это видно в отчёте.
     */
    /**
     * Системное задание grounded-режима: ответ, который можно проверить по фрагментам.
     *
     * Правило о **полноте** (2) появилось после живого прогона и держится на нём же. Первая версия
     * задания требовала только «не выдумывать», и модель поняла это как «сказать поменьше»: на вопрос
     * о костюме она называла трость и молчала о волосах до плеч, хотя оба сведения лежали в одном
     * процитированном предложении. Ответ становился доказуемым и неполным одновременно, а мера дня
     * («можно ли проверить ответ») — это не мера осторожности: сведения, которые фрагмент называет,
     * обязаны попасть в ответ, иначе проверять будет нечего. Поэтому задание требует назвать всё,
     * что отвечает на вопрос, и на каждое сведение дать свою цитату.
     *
     * Требование дословности (3) и «своя цитата на утверждение» (4) — не стилистика: проверка
     * ([Citations.validate]) ищет цитату в тексте чанка по буквам, и пересказ она не засчитает
     * (живой прогон: «женщина умерла за границей» вместо «скончалась в Париже» — не подтверждение).
     * Утверждение без цитаты не засчитывается вовсе, и задание говорит об этом прямо, чтобы модель
     * не считала отброшенное утверждение выполненным пунктом.
     *
     * Метаданные источника (5) модель не пишет по построению: глава, страницы и идентификатор чанка
     * собираются из метаданных ([SourceRef.of]), и придумать их модель не может — этих полей в её
     * ответе просто нет. Это и есть §4 задания: источник формирует система.
     */
    val GROUNDED_SYSTEM: String = "Ты отвечаешь на вопрос по роману Ф. М. Достоевского «Бесы» " +
        "строго по фрагментам, которые тебе даны.\n" +
        "Правила:\n" +
        "1. Отвечай только тем, что есть во фрагментах, и не дополняй ответ тем, что помнишь о романе.\n" +
        "2. Ответь на вопрос полно: назови все сведения фрагментов, которые на него отвечают, " +
        "а не только главное. Если фрагмент называет несколько обстоятельств (кто, что, где, когда, " +
        "сколько), каждое обстоятельство — отдельное утверждение и отдельная цитата.\n" +
        "3. Каждое утверждение подтверди цитатой из фрагмента: приведи кусок его текста дословно, " +
        "слово в слово. Цитата может быть предложением или его частью, но пересказ, переставленные " +
        "слова и вставки не засчитываются: цитата ищется в тексте фрагмента по буквам.\n" +
        "4. Утверждение, для которого во фрагментах нет дословной цитаты, в ответ не включай.\n" +
        "5. Назови номер фрагмента, из которого взята цитата. Больше ничего об источнике не пиши: " +
        "страницы, главу и идентификатор подставит система.\n" +
        "6. Если ответа во фрагментах нет, верни insufficient: true и не придумывай ответ. " +
        "Лучше признать нехватку сведений, чем ответить по памяти.\n" +
        "Ответ верни одним объектом JSON без пояснений вокруг:\n" +
        "{\"answer\": \"ответ целиком\", \"insufficient\": false, \"claims\": " +
        "[{\"claim\": \"первое утверждение\", \"fragment\": 1, \"quote\": \"дословная цитата из фрагмента 1\"}, " +
        "{\"claim\": \"второе утверждение\", \"fragment\": 1, \"quote\": \"другая дословная цитата\"}]}\n" +
        "Если ответа нет: {\"answer\": \"\", \"insufficient\": true, \"claims\": []}"

    /**
     * Сообщения grounded-режима: то же правило с цитатами и тот же блок фрагментов, что в дне 23.
     *
     * Фрагменты уходят тем же способом ([fragments]) и с теми же номерами, что в дне 23: номера —
     * это то, на что модель ссылается в утверждениях, и совпадение нумерации с контекстом дня 23
     * позволяет сравнивать два режима на одной выдаче. Вопрос в сообщении — исходный: переписанный
     * запрос служил поиску, и отвечать модель должна на вопрос человека.
     */
    fun grounded(question: String, sources: List<Source>): List<ChatMessage> = listOf(
        ChatMessage(role = SYSTEM, content = GROUNDED_SYSTEM),
        ChatMessage(role = USER, content = fragments(sources) + "\n\n" + QUESTION_PREFIX + question)
    )

    /** Сообщения режима без RAG: то же системное задание без правил и вопрос без фрагментов. */
    fun withoutContext(question: String): List<ChatMessage> = listOf(
        ChatMessage(role = SYSTEM, content = SYSTEM_WITHOUT_CONTEXT),
        ChatMessage(role = USER, content = QUESTION_PREFIX + question)
    )

    /**
     * Сообщения режима с RAG: системное правило и вопрос вместе с найденными фрагментами.
     *
     * Вопрос в пользовательском сообщении — исходный, а не тот, которым искали: переписанный запрос
     * ([Rewrite]) служит поиску, а отвечать модель должна на вопрос человека. Подстановка переписанного
     * запроса здесь была бы незаметной подменой задания — сравнение мерило бы ответ на другой вопрос.
     */
    fun withContext(question: String, sources: List<Source>): List<ChatMessage> = listOf(
        ChatMessage(role = SYSTEM, content = SYSTEM_WITH_CONTEXT),
        ChatMessage(role = USER, content = fragments(sources) + "\n\n" + QUESTION_PREFIX + question)
    )

    /**
     * Сообщения режима с RAG, когда фрагментов не осталось: фильтр убрал всех кандидатов.
     *
     * Правило то же, что в [SYSTEM_WITH_CONTEXT] (опираться только на фрагменты), но пользовательское
     * сообщение говорит прямо, что фрагментов нет. Пустой блок фрагментов этого не говорит: модель
     * видела бы заголовок «Ниже даны фрагменты» без фрагментов и могла бы ответить по памяти —
     * а именно этого задание и просит не делать. Формулировка ожидаемого ответа здесь не подсказана:
     * сообщение описывает положение дел, а слова выбирает модель, и проверка ([Check]) принимает
     * любой из способов сказать, что сведений нет.
     */
    fun withEmptyContext(question: String): List<ChatMessage> = listOf(
        ChatMessage(role = SYSTEM, content = SYSTEM_WITH_CONTEXT),
        ChatMessage(
            role = USER,
            content = "По этому вопросу в проиндексированных источниках не осталось ни одного " +
                "фрагмента, прошедшего отбор: поиск не нашёл ничего достаточно близкого к вопросу.\n" +
                "Скажи об этом прямо и не отвечай по памяти.\n\n" + QUESTION_PREFIX + question
        )
    )

    /**
     * Блок фрагментов в том виде, в каком его видит модель: номер, место в книге и текст.
     *
     * Номер в квадратных скобках — тот же, каким модель называет источник в ответе, и он же
     * разбирается проверкой ссылок ([Check.citedFragments]). По этим номерам отчёт связывает
     * названные моделью источники со страницами и видит, попала ли в ответ база или общие слова.
     */
    fun fragments(sources: List<Source>): String = sources.joinToString("\n\n") { source ->
        "[${source.rank}] ${source.label}\n${source.text}"
    }

    private const val SYSTEM = "system"
    private const val USER = "user"
}
