package com.osvin.aichallenge.rag.chat

import com.osvin.aichallenge.models.ChatMessage
import com.osvin.aichallenge.rag.GroundedAnswer
import com.osvin.aichallenge.rag.Prompt
import com.osvin.aichallenge.rag.Source

/**
 * Промпты мини-чата: ответ по базе, извлечение памяти задачи и переписывание запроса по истории.
 *
 * Задание дня 25 — тот же grounded-ответ дня 24, но в разговоре, и это задаёт здесь главное решение:
 * правила цитирования **не переписываются**, а берутся готовыми ([Prompt.GROUNDED_RULES]). Чат
 * спрашивает модель теми же правилами 1–6 и своей схемой ответа, в которой добавлено поле `kind`,
 * а к правилам добавлены 7–9 — про цель разговора, память задачи и вопросы о самом разговоре.
 * Плодить второй экземпляр правил было бы ошибкой: проверка цитат ([Citations.validate]) у чата та же,
 * и требование, сформулированное иначе, мерилось бы другой меркой.
 *
 * Разница между днём 24 и чатом видна в трёх местах промпта, и все три — про разговор, а не про ответ:
 * в системное сообщение идёт блок памяти задачи, между системой и вопросом встаёт история последних
 * ходов, и у вопроса появляется вид — о книге он или о разговоре. Фрагменты по-прежнему относятся
 * только к текущему вопросу и нумеруются с единицы: номера, унаследованные из старых ответов, ничего
 * не значат, и об этом модель предупреждает отдельной строкой [HISTORY_NOTE].
 */
object ChatPrompt {

    /**
     * Открывающая фраза чата: задание дня 24, сказанное про разговор.
     *
     * Отдельно от [Prompt.GROUNDED_RULES] намеренно: правила — общий текст двух режимов, а первая
     * фраза описывает положение дел («идёт разговор по шагам»), и в одиночном ответе дня 24 её быть
     * не должно — там разговора нет.
     */
    const val CHAT_TASK: String = "Ты ведёшь диалог по роману Ф. М. Достоевского «Бесы» " +
        "строго по фрагментам, которые тебе дают.\n" +
        "Разговор идёт по шагам и у него есть цель, правила и термины — они даны в блоке памяти " +
        "задачи, если он есть.\n"

    /**
     * Правила 7–9 — то, чем чат отличается от одиночного ответа.
     *
     * Нумерация продолжает правила [Prompt.GROUNDED_RULES], а не начинается заново: для модели это
     * один список, и разрыв нумерации читался бы как два отдельных задания. Правило 7 — про цель:
     * провал длинного разговора выглядит не как ошибка в факте, а как потеря предмета (модель
     * отвечает на реплику и забывает, о чём был разговор), поэтому цель названа прямо и запрещено
     * начинать объяснение заново. Правило 8 делает память задачи частью задания: термин, который
     * человек зафиксировал, — это договорённость, а не подсказка. Правило 9 разводит два вида
     * вопросов: о книге (правила 1–6, цитаты) и о самом разговоре (ответ по памяти, без цитат) —
     * без него вопрос «что мы разбираем?» получал бы честный отказ «во фрагментах этого нет»,
     * то есть ответ не на заданный вопрос. К разговору отнесены и реплики-предписания — «дальше
     * отвечай коротко», «под этим словом я имею в виду вот кого»: это не вопрос о книге, но ответ
     * на них нужен, и без правила 9 они попадали бы в отказ, который человек читает как отказ
     * вести разговор.
     */
    const val CHAT_RULES: String = "7. Держи цель разговора: вопрос человека — очередной шаг к цели " +
        "из памяти задачи, а не новый разговор. Не начинай объяснять с начала и не пересказывай " +
        "уже сказанное, если человек об этом не просит.\n" +
        "8. Термины и правила из памяти задачи — часть задания: используй зафиксированный термин " +
        "в его значении и соблюдай правила, которые человек установил.\n" +
        "9. Вопрос бывает не о книге, а о самом разговоре: «что мы разбираем», «какие правила " +
        "ты держишь», «что мы уже выяснили», а также просьбы поставить правило или закрепить " +
        "термин («дальше отвечай коротко», «под этим словом я имею в виду вот кого»). На такие " +
        "реплики отвечай по памяти задачи — коротко подтверди, что понял, — и верни " +
        "kind: \"dialogue\" без утверждений и цитат. Всё остальное — вопросы о книге, и для них " +
        "действуют правила 1–6.\n"

    /** Схема ответа чата: та же форма дня 24 плюс вид ответа (`kind`). */
    const val CHAT_SCHEMA: String = "Ответ верни одним объектом JSON без пояснений вокруг:\n" +
        "{\"kind\": \"base\", \"answer\": \"ответ целиком\", \"insufficient\": false, " +
        "\"claims\": [{\"claim\": \"первое утверждение\", \"fragment\": 1, " +
        "\"quote\": \"дословная цитата из фрагмента 1\"}]}\n" +
        "Ответ о разговоре: {\"kind\": \"dialogue\", \"answer\": \"ответ целиком\", " +
        "\"insufficient\": false, \"claims\": []}\n" +
        "Если ответа во фрагментах нет: {\"kind\": \"base\", \"answer\": \"\", " +
        "\"insufficient\": true, \"claims\": []}"

    /** Системное сообщение чата целиком: задание, общие правила, правила разговора, схема. */
    val CHAT_SYSTEM: String = CHAT_TASK + Prompt.GROUNDED_RULES + CHAT_RULES + CHAT_SCHEMA

    /**
     * Строка перед историей: предупреждение о номерах фрагментов в старых ответах.
     *
     * Без неё модель копирует «[2]» из своего прошлого ответа, и номер указывает на фрагмент,
     * которого в текущем контексте может не быть. Проверка цитат такой номер отбросит (утверждение
     * не подтвердится), и это правильный исход — но это потеря утверждения из-за путаницы, а не из-за
     * выдумки, и предупредить дешевле, чем терять ответы.
     */
    const val HISTORY_NOTE: String = "Ниже — уже сказанное в этом разговоре. Номера фрагментов " +
        "в прошлых ответах относятся к фрагментам, которые давались тогда, и к текущим не относятся."

    /**
     * Что видит модель, когда фильтр не оставил ни одного фрагмента.
     *
     * Пустой блок фрагментов этого не сообщает: модель видела бы заголовок без текста и могла бы
     * ответить по памяти — ровно то, что задание запрещает. Поэтому положение дел называется прямо,
     * и рядом остаётся лазейка для вопроса о разговоре: он отвечается по памяти задачи и фрагментов
     * не требует.
     */
    const val EMPTY_CONTEXT_NOTE: String = "По этому вопросу в проиндексированных источниках " +
        "не осталось ни одного фрагмента, прошедшего отбор: поиск не нашёл ничего достаточно " +
        "близкого к вопросу.\n" +
        "Если вопрос о книге — верни insufficient: true и не отвечай по памяти. " +
        "Если вопрос о самом разговоре — ответь по памяти задачи и верни kind: \"dialogue\"."

    /**
     * Сообщения ответа: то же устройство, что у [Prompt.grounded], плюс память задачи и история.
     *
     * Порядок не случаен. Системное задание идёт первым, память задачи — сразу за ним: это правила
     * разговора, и они должны быть прочитаны до истории, иначе история читается как самостоятельный
     * разговор. История — настоящими парами «вопрос — ответ», а не пересказом: модель продолжает
     * диалог, а не разбирает чужой лог, и в живом прогоне дня 25 видно, что неполный вопрос
     * («а кто его отец?») она понимает именно по этим парам. Фрагменты — только текущего вопроса
     * и в последнем сообщении, как в дне 24: отвечать модель должна на вопрос человека, а номера
     * фрагментов — на то, что дано сейчас.
     */
    fun chat(
        question: String,
        sources: List<Source>,
        memory: TaskMemory,
        window: List<DialogueMessage>,
        emptyContext: Boolean = false
    ): List<ChatMessage> {
        val messages = ArrayList<ChatMessage>()
        messages += ChatMessage(role = SYSTEM, content = CHAT_SYSTEM)
        memory.render().takeIf { it.isNotEmpty() }?.let { messages += ChatMessage(role = SYSTEM, content = it) }
        messages += history(window)
        val context = if (emptyContext) EMPTY_CONTEXT_NOTE else Prompt.fragments(sources)
        messages += ChatMessage(role = USER, content = context + "\n\n" + Prompt.QUESTION_PREFIX + question)
        return messages
    }

    /**
     * История окна: пары «вопрос — ответ» в том виде, в каком они были сказаны.
     *
     * Отказ тоже попадает в историю, и текстом отказа, а не пропуском: разговор, в котором человеку
     * однажды ответили «во фрагментах этого нет», не должен читаться как разговор, где этого вопроса
     * не было, — иначе модель ответит на него второй раз как на новый. Текст берётся общий
     * ([GroundedAnswer.REFUSAL_TEXT]), чтобы чат не завёл формулировку отказа, отличную от дня 24.
     */
    fun history(window: List<DialogueMessage>): List<ChatMessage> {
        if (window.isEmpty()) return emptyList()
        val messages = ArrayList<ChatMessage>()
        messages += ChatMessage(role = SYSTEM, content = HISTORY_NOTE)
        window.forEach { replica ->
            messages += ChatMessage(role = replica.role.modelRole(), content = replica.content)
        }
        return messages
    }

    /**
     * Задание извлечения памяти задачи: разговор превращается в цель, уточнения, правила и термины.
     *
     * Состояние запрашивается **целиком**, а не приращением: модель читает разговор и отвечает,
     * что должно быть в памяти. Приращение («что нового») на каждой реплике давало бы дрейф — память,
     * которую дописывают куски, со временем перестаёт быть связной, а проверить её нечем. Две оговорки
     * в задании важные. Первая: цель — про разговор **в целом**, и модель не должна переписывать её
     * на каждой реплике под последний вопрос (иначе к десятому ходу останется описание одного факта).
     * Вторая: уже зафиксированное не выбрасывается — слияние ([TaskMemory.merge]) от потери защищает,
     * но модель, которая не пересказала старое, теряет не память, а ясность: старое останется,
     * но с пометкой «модель его больше не называет».
     *
     * Требование «ничего не выдумывать» здесь сильнее, чем где-либо в дне: память задачи попадает
     * в **каждый** последующий запрос, и придуманное ограничение будет исполняться как правило
     * до конца разговора. Поэтому в задании прямо сказано: чего в разговоре не было, в память
     * не попадает, а пустые списки — нормальный ответ.
     */
    const val MEMORY_SYSTEM: String = "Ты ведёшь память задачи в разговоре по роману " +
        "Ф. М. Достоевского «Бесы». Прочитай разговор и верни состояние памяти целиком.\n" +
        "Поля:\n" +
        "- goal: одной фразой — чего человек хочет от этого разговора в целом, а не пересказ " +
        "последнего вопроса. Если цель уже была сформулирована и человек её не менял, верни её же " +
        "слово в слово.\n" +
        "- clarifications: что человек уточнил по ходу разговора — короткие фразы, по одной мысли.\n" +
        "- constraints: только те правила и рамки, которые человек установил сам в этом разговоре, " +
        "например «отвечай только по первой главе» или «не больше трёх пунктов». Правила из твоего " +
        "собственного задания (цитировать, не выдумывать, признавать нехватку сведений) сюда " +
        "не попадают: их установил не человек, и в памяти они выглядели бы как его требования.\n" +
        "- terms: термины этого разговора и их значения — пары " +
        "{\"term\": \"слово\", \"meaning\": \"что оно значит в разговоре\"}.\n" +
        "Ничего не выдумывай: то, чего в разговоре не было, в память не попадает. Пустые списки — " +
        "это нормальный ответ. Уже зафиксированное не выбрасывай.\n" +
        "Ответ верни одним объектом JSON без пояснений вокруг:\n" +
        "{\"goal\": \"цель разговора\", \"clarifications\": [\"...\"], \"constraints\": [\"...\"], " +
        "\"terms\": [{\"term\": \"...\", \"meaning\": \"...\"}]}"

    /**
     * Запрос на извлечение памяти: прежняя память, разговор и новая реплика.
     *
     * Прежняя память даётся текстом, а не JSON: модель читает её как то, что уже записано, и повторяет
     * в ответе — так слияние не зависит от того, догадается ли модель переписать старое своими
     * словами. Реплика человека идёт последней и отдельной строкой: в окне истории она уже есть,
     * но память меняется именно ею, и повторять её как «новое сообщение» дешевле, чем объяснять
     * модели, какая из реплик окна новая.
     */
    fun memory(memory: TaskMemory, window: List<DialogueMessage>, question: String): List<ChatMessage> {
        val dialogue = window.joinToString("\n") { replica -> "${replica.role.title}: ${replica.content}" }
        val previous = memory.render().takeIf { it.isNotEmpty() } ?: "(память пока пуста)"
        return listOf(
            ChatMessage(role = SYSTEM, content = MEMORY_SYSTEM),
            ChatMessage(
                role = USER,
                content = "Память, которая есть сейчас:\n$previous\n\n" +
                    (if (dialogue.isEmpty()) "" else "Разговор:\n$dialogue\n\n") +
                    "Новое сообщение человека: $question"
            )
        )
    }

    /**
     * Задание переписывания запроса по истории.
     *
     * В дне 22 переписывание решало другую задачу — разговорную форму вопроса превращало в запрос
     * к базе («Расскажи о Степане Трофимовиче» → «Степан Трофимович Верховенский»). В чате появляется
     * то, чего в одиночном вопросе быть не может: **неполный** вопрос, который опирается на прошлые
     * реплики. «А сколько ему было лет?» без истории не ищется вовсе — в нём нет ни одного имени,
     * и поиск вернёт что попало. Поэтому правило 2 требует раскрыть местоимения и неполные имена
     * по последним репликам, а правило 4 запрещает выдумывать: раскрытие — это подстановка того,
     * что уже сказано, а не догадка о том, кого человек имел в виду.
     */
    const val REWRITE_SYSTEM: String = "Ты готовишь поисковый запрос по разговору о романе " +
        "Ф. М. Достоевского «Бесы».\n" +
        "Правила:\n" +
        "1. Сохрани смысл текущего вопроса; не добавляй того, чего в нём нет.\n" +
        "2. Если вопрос опирается на разговор («а сколько ему было лет?»), раскрой местоимения " +
        "и неполные имена по последним репликам: подставь имена и предмет, о которых шла речь.\n" +
        "3. Если в памяти задачи есть термин, значение которого зафиксировано, используй значение, " +
        "а не само слово.\n" +
        "4. Верни одну строку ключевых слов без пояснений и без кавычек."

    /**
     * Запрос на переписывание: память, последние реплики и текущий вопрос.
     *
     * Память идёт и сюда: значение термина меняет запрос к поиску («сын» → «Пётр Степанович»),
     * и без блока памяти переписывание вернуло бы слово в первом попавшемся значении.
     */
    fun rewrite(question: String, memory: TaskMemory, window: List<DialogueMessage>): List<ChatMessage> {
        // Переписывателю идут только реплики человека, а не весь разговор: его задача — раскрыть
        // неполный вопрос по тому, что человек уже назвал, а ответы ассистента — это уже выводы
        // системы, и подставлять их в запрос значило бы искать по своим же словам, а не по репликам.
        val dialogue = window.filter { replica -> replica.role == DialogueRole.USER }
            .joinToString("\n") { replica -> "${replica.role.title}: ${replica.content}" }
        val terms = memory.render().takeIf { it.isNotEmpty() } ?: "(память пока пуста)"
        return listOf(
            ChatMessage(role = SYSTEM, content = REWRITE_SYSTEM),
            ChatMessage(
                role = USER,
                content = "Память задачи:\n$terms\n\n" +
                    (if (dialogue.isEmpty()) "" else "Последние вопросы:\n$dialogue\n\n") +
                    "Текущий вопрос: $question"
            )
        )
    }

    private const val SYSTEM = "system"
    private const val USER = "user"
    private const val ASSISTANT = "assistant"

    /**
     * Роль реплики разговора в ролях запроса к модели.
     *
     * Перевод стоит здесь, а не в [DialogueMessage], потому что слова «user» и «assistant» — это
     * словарь запроса к модели, и он принадлежит промпту: истории про роли знать не нужно, чем
     * именно называет их API.
     */
    private fun DialogueRole.modelRole(): String = when (this) {
        DialogueRole.USER -> USER
        DialogueRole.ASSISTANT -> ASSISTANT
    }
}
