package com.osvin.aichallenge.models.config

/**
 * Конфигурация приложения по умолчанию: значения агента (модель, лимиты,
 * температура, тарифы) и параметры запуска сервера.
 */
object AppConfig {
    const val DEFAULT_MODEL = "deepseek-v4-flash"
    const val DEFAULT_TEMPERATURE = 0.7

    /**
     * Бюджет ответа по умолчанию: компромисс цены и места под рассуждения.
     * У thinking-модели рассуждения тратят тот же бюджет, поэтому на 2000 токенов
     * обычный вопрос («какие позиции в волейболе ты знаешь?») не успевал дойти
     * до текста и ответ приходил пустым.
     */
    const val DEFAULT_MAX_TOKENS = 8192

    /**
     * Верхняя граница `max_tokens`, которую агент принимает от клиента (граница
     * самого API — 393 216, но столько за раз не нужно). Поднята с 8192, потому
     * что у thinking-модели рассуждения идут из того же бюджета: на живом прогоне
     * весь бюджет 8192 ушёл на рассуждения, текста не осталось, и вызов упал с
     * `EmptyReplyException` — а подсказка «увеличьте max_tokens» должна быть
     * выполнима.
     */
    const val MAX_TOKEN_CEILING = 32_768
    const val MAX_STOP_SEQUENCES = 16

    /**
     * Сколько раз за один запуск агент выполняет вызовы инструментов, которые просит модель.
     *
     * Инструменты стоят денег и времени: каждый раунд — это ещё один запрос со всей перепиской,
     * а модель может просить их бесконечно («позови ещё раз, вдруг теперь получится»). Поэтому
     * раундов конечное число, и после них инструменты больше не предлагаются: модель отвечает
     * тем, что уже есть. Три, а не один: цель раунда может зависеть от результата предыдущего —
     * сначала узнать, что доступно, потом попросить нужное.
     */
    const val MAX_TOOL_ROUNDS = 3
    const val DEFAULT_PORT = 8080
    const val DEFAULT_HOST = "0.0.0.0"
}
