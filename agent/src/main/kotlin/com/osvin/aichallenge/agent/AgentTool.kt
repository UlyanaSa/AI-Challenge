package com.osvin.aichallenge.agent

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonObject

/**
 * Инструмент, который агент предлагает модели: имя, описание, схема аргументов и вызов.
 *
 * Агент не знает, откуда инструмент взялся: он объявляет модели список [AgentTool], получает
 * от неё вызов и отдаёт ей результат. Поэтому протокол доставки инструментов (MCP со своим
 * транспортом, сессией и процессами) остаётся снаружи агента: адаптер живёт там, где известны
 * обе стороны, и агент не меняется, когда меняется способ подключения инструментов, — только
 * когда меняется сам способ работы с ними.
 *
 * @param name Имя для вызова: по нему модель выбирает инструмент, и по нему же агент находит,
 *        что выполнять.
 * @param description Что инструмент отдаёт — словами, по которым модель решает, нужен ли он.
 * @param parameters Схема аргументов (JSON Schema): её видит модель, поэтому имена, типы и
 *        допустимые значения объявляет тот, кто инструмент знает, а не агент.
 * @param call Вызов: аргументы, разобранные из ответа модели, — то, что уйдёт ей следующим
 *        сообщением ([ToolOutcome]).
 */
data class AgentTool(
    val name: String,
    val description: String,
    val parameters: JsonObject = JsonObject(emptyMap()),
    val call: suspend (JsonObject) -> ToolOutcome
)

/**
 * Ответ инструмента: то, что агент отдаёт модели следующим сообщением.
 *
 * Отказ — тоже ответ. Инструмент, который не смог получить данные (нет доступа, нет сети,
 * сервис ответил ошибкой), возвращает текст причины с [isError], и модель отвечает по нему.
 * Иначе недоступный внешний сервис отменял бы ответ пользователю целиком, хотя вопрос был
 * не только о нём: «покажи мои репозитории и объясни, что такое rebase» — половина ответа
 * не зависит от того, ответил ли GitHub.
 *
 * @param text Текст для модели: данные инструмента или причина отказа.
 * @param isError Инструмент ответил отказом: данных нет.
 */
data class ToolOutcome(val text: String, val isError: Boolean = false)

/**
 * Отчёт о вызовах инструментов в этом запуске агента.
 *
 * Вызовы стоят токенов: результат возвращается модели ещё одним запросом, поэтому запуск
 * с инструментами — это несколько обращений к API. Без этого отчёта расход был бы показан
 * меньше настоящего, а без списка вызовов не было бы видно, чем именно он вырос.
 *
 * @param calls Что вызывалось и чем кончилось — по порядку вызовов.
 * @param rounds Сколько раундов общения с моделью заняли вызовы; 0 — модель их не просила.
 * @param tokens Токены всех раундов, кроме первого: первый раунд — обычный запрос, остальные
 *        появились из-за инструментов.
 */
@Serializable
data class ToolsReport(
    @SerialName("calls") val calls: List<ToolCallRecord> = emptyList(),
    @SerialName("rounds") val rounds: Int = 0,
    @SerialName("tokens") val tokens: Int = 0
)

/**
 * Один вызов инструмента в отчёте.
 *
 * @param name Имя инструмента, который выбрала модель.
 * @param failed Инструмент ответил отказом: данных нет, и модель отвечает по причине.
 */
@Serializable
data class ToolCallRecord(
    @SerialName("name") val name: String,
    @SerialName("failed") val failed: Boolean = false
)
