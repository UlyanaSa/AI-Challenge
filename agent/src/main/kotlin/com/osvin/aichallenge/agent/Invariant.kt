package com.osvin.aichallenge.agent

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/** Заголовок блока инвариантов: по нему правила видно и в промпте, и в логе. */
private const val INVARIANTS_HEADER = "Инварианты проекта (нарушать нельзя, решение обязано им соответствовать):"

/**
 * Вид инварианта: что за правило объявлено — устройство проекта, принятое решение,
 * ограничение стека или правило продукта.
 *
 * Видов ровно четыре, и названы они так же, как в задании дня, — в коде, на проводе
 * и в интерфейсе. По этим видам человек выбирает, куда отнести правило ([InvariantWriter]),
 * и по ним же видно, что именно нарушено ([GuardViolation]): без общего списка видов
 * «нарушено бизнес-правило» и «нарушено правило бизнеса» были бы разными строками отчёта.
 *
 * Подписи и пояснения живут только здесь: интерфейс берёт их из каталога снимка
 * ([InvariantKind.info]), поэтому разойтись с сервером они не могут.
 *
 * @param wire Значение вида в служебном вызове, на проводе и в отчёте агента.
 * @param title Название вида для блока промпта, интерфейса и логов.
 * @param hint Пояснение к названию — то, что стоит в скобках в каталоге видов: «архитектура
 *        (как устроен проект: общий код, модули и их границы)».
 */
enum class InvariantKind(val wire: String, val title: String, val hint: String) {

    /** Как устроен проект: общий код и границы модулей. */
    ARCHITECTURE("architecture", "архитектура", "как устроен проект: общий код, модули и их границы"),

    /** Принятое техническое решение, которое в работе не пересматривают. */
    DECISION("decision", "решение", "принятое решение, которое в работе не пересматривают"),

    /** Чем разрешено пользоваться: язык, библиотеки, версии. */
    STACK("stack", "стек", "чем разрешено пользоваться: язык, библиотеки, версии"),

    /** Правило продукта: что можно делать с данными и результатом. */
    BUSINESS("business", "бизнес-правило", "правило продукта: что можно делать с данными пользователя");

    companion object {

        /**
         * Вид по значению провода; null — вид неизвестен, и правило по нему не принимается
         * ([InvariantRules.normalize]): подпись такого вида неоткуда взять, а в блок промпта
         * он попал бы безымянным.
         */
        fun ofWire(value: String?): InvariantKind? =
            entries.firstOrNull { it.wire == value?.trim()?.lowercase() }

        /**
         * Каталог видов: уезжает клиенту вместе со снимком ([InvariantSnapshot]) и уходит
         * в инструкцию проверки ([InvariantGuard]). Порядок — как объявлены виды, поэтому
         * разделы шторки инвариантов идут от устройства проекта к правилам продукта.
         */
        val info: List<InvariantKindInfo> = entries.map { InvariantKindInfo(it.wire, it.title, it.hint) }
    }
}

/**
 * Инвариант проекта: правило, которое ассистент не имеет права нарушить — как устроен
 * проект, какое решение принято, чем разрешено пользоваться, что нельзя делать с данными.
 *
 * С памятью ([MemoryRecord]) и профилем ([UserProfile]) инварианты не смешиваются, потому
 * что приходят в диалог не из него:
 *
 * - память наполняет модель: записи она достаёт из переписки и переписывает по стратегии
 *   контекста, поэтому память — следствие диалога, и диалог же решает, уйдёт она в запрос
 *   или нет;
 * - профиль объявляет человек, но он про него самого: предпочтения, по которым модель
 *   выбирает форму ответа;
 * - инвариант объявляет человек, и он про работу: правило действует над диалогом, а не
 *   обсуждается в нём. Модель его не извлекает и переписать в ответе не может, человек
 *   его в переписке не пересказывает, а «забыть» по стратегии нельзя.
 *
 * Отсюда и хранение: правила лежат своим хранилищем ([InvariantStore]) отдельно от истории
 * сообщений, потому что история — ровно то, что стратегия режет, ветвит и сжимает, а правило
 * обязано дойти до модели в каждом запросе, какая бы стратегия ни была выбрана. Тем же и
 * объясняется место правила в запросе: оно уходит системным сообщением сразу после профиля
 * ([LlmAgent]) — не реплика в диалоге, а условие, которому обязан соответствовать ответ.
 *
 * Инвариант никто не выводит на глаз: формулировку пишет человек ([InvariantWriter]),
 * а конфликт запроса с ней проверяет отдельный служебный вызов ([InvariantGuard]) — по его
 * вердикту агент добавляет в запрос правило отказа, и отказ получает причину, названную кодом.
 *
 * @param kind Вид правила: значение [InvariantKind.wire].
 * @param value Формулировка правила: что именно нельзя нарушать.
 */
@Serializable
data class Invariant(
    @SerialName("kind") val kind: String,
    @SerialName("value") val value: String
) {
    companion object {

        /**
         * Правила, с которыми этот проект начинает работу, — по одному на каждый вид
         * ([InvariantKind]).
         *
         * Набор существует ради того, ради чего заведены и сами инварианты: правила проекта
         * действуют с первого запуска, а не после того, как человек их сформулирует, — иначе
         * первый же запрос к ассистенту мог бы попросить Java или передать данные наружу.
         * Лежат правила рядом с типом, который перечисляют, но подставляет их не агент, а тот,
         * кто владеет данными: сервер кладёт набор в хранилище один раз при первом запуске.
         * Агент читает из хранилища как есть ([InvariantStore]) — это и оставляет его честным:
         * правила ему назначает проект, а не он сам себе.
         */
        val DEFAULT: List<Invariant> = listOf(
            Invariant(
                InvariantKind.ARCHITECTURE.wire,
                "один общий код на Kotlin Multiplatform в commonMain и тонкие платформенные адаптеры; " +
                    "сервер на Ktor, агент — отдельный модуль, сервер к нему только адаптер HTTP"
            ),
            Invariant(
                InvariantKind.DECISION.wire,
                "состояние и правила — память, профиль, задача, сами инварианты — живут на сервере " +
                    "и уходят в модель системными сообщениями; клиент их не подставляет и в теле " +
                    "запроса не передаёт"
            ),
            Invariant(
                InvariantKind.STACK.wire,
                "только Kotlin: без Java и RxJava; версии — из version catalog; " +
                    "новых зависимостей не добавлять без явной просьбы"
            ),
            Invariant(
                InvariantKind.BUSINESS.wire,
                "данные пользователя не уходят третьим лицам: наружу уходит только запрос к модели, " +
                    "долговременное состояние хранится на своём сервере"
            )
        )
    }
}

/**
 * Вид инварианта в каталоге: как он называется и какие правила в него пишут.
 *
 * Каталог собирается из [InvariantKind] и уезжает клиенту вместе со снимком ([InvariantSnapshot]):
 * выбор вида при записи правила и разделы шторки рисуются по нему, поэтому своей копии
 * таблицы видов у клиента нет — подписи и пояснения не могут разойтись с сервером.
 *
 * @param kind Вид: значение [InvariantKind.wire], оно же уходит обратно при записи правила.
 * @param title Название вида для интерфейса и логов.
 * @param hint Пояснение к названию из задания дня.
 */
@Serializable
data class InvariantKindInfo(
    @SerialName("kind") val kind: String,
    @SerialName("title") val title: String,
    @SerialName("hint") val hint: String
)

/**
 * Снимок инвариантов профиля: сами правила и каталог видов. Тем же ответом сервер отвечает
 * и на чтение, и на явную запись, и на удаление правила, поэтому шторка инвариантов всегда
 * берёт состояние из ответа сервера, а не собирает его сама.
 *
 * Умолчаний у полей нет намеренно: правила этого проекта равны [Invariant.DEFAULT], а каталог —
 * [InvariantKind.info], и значение, равное объявленному умолчанию, kotlinx.serialization
 * на провод не пишет — клиент получил бы снимок без видов и без правил, а своей копии
 * умолчания у него нет. Пишет оба поля [InvariantWriter].
 *
 * @param invariants Правила профиля: что лежит в хранилище инвариантов сейчас.
 * @param kinds Каталог видов: порядок разделов шторки и их подписи.
 */
@Serializable
data class InvariantSnapshot(
    @SerialName("invariants") val invariants: List<Invariant>,
    @SerialName("kinds") val kinds: List<InvariantKindInfo>
)

/** Чем кончилась проверка правила при явной записи: инвариантом или отказом с причиной. */
sealed interface InvariantDecision {

    /** Правило прошло проверки и легло в список правил. */
    data class Accepted(val invariant: Invariant) : InvariantDecision

    /** Вид неизвестен, текст пуст или слишком длинен: причина — в [reason]. */
    data class Rejected(val reason: String) : InvariantDecision
}

/**
 * Пределы списка правил и само правило как строка промпта.
 *
 * Пределы жёсткие — это не подсказка интерфейсу, а причина отказа: правило проекта читает
 * модель в каждом запросе, поэтому список не может расти как история. Формулировку при этом
 * никто не переписывает и не обрезает: инвариант не выводят из переписки, его объявляет
 * человек ([InvariantWriter]), и «починенное» правило читалось бы не так, как его написали.
 */
object InvariantRules {

    /** Сколько правил держит список: дальше это уже не правила проекта, а второй промпт. */
    const val MAX_INVARIANTS = 20

    /** Предел формулировки: инвариант — одна фраза, а не раздел договора. */
    const val MAX_VALUE = 300

    /** Причина отказа: вид правила не из четырёх, названных в задании. */
    const val UNKNOWN_KIND = "вид инварианта неизвестен"

    /** Причина отказа: формулировка правила пуста. */
    const val EMPTY_VALUE = "инвариант пуст"

    /** Причина отказа: формулировка не влезает в предел длины. */
    const val TOO_LONG = "формулировка длиннее $MAX_VALUE символов — инвариант должен быть одной фразой"

    /** Причина отказа: в списке нет места. */
    const val TOO_MANY = "инвариантов уже $MAX_INVARIANTS — больше не поместится: сначала уберите лишние"

    /**
     * Приводит правило к границам списка: известный вид, непустой текст и предел длины.
     *
     * Пустой вид считается неизвестным, а не «любым»: вид правила выбирает человек, и правило
     * без вида некуда было бы отнести — в блоке промпта оно осталось бы без подписи.
     */
    fun normalize(kind: String?, value: String?): InvariantDecision {
        val invariantKind = InvariantKind.ofWire(kind) ?: return InvariantDecision.Rejected(UNKNOWN_KIND)
        val text = value?.trim().orEmpty()
        if (text.isEmpty()) return InvariantDecision.Rejected(EMPTY_VALUE)
        if (text.length > MAX_VALUE) return InvariantDecision.Rejected(TOO_LONG)
        return InvariantDecision.Accepted(Invariant(invariantKind.wire, text))
    }

    /**
     * Сливает прежние правила с новым: та же формулировка заменяет прежнее правило и становится
     * последним, новый текст добавляется отдельным правилом. Ключ — сама формулировка, как
     * у записи памяти: разметки у инварианта нет, поэтому повтор опознаётся по тексту, а
     * пересказанное правило становится вторым — видно в шторке, и лишнее можно убрать.
     */
    fun add(existing: List<Invariant>, invariant: Invariant): List<Invariant> {
        val merged = LinkedHashMap<String, Invariant>()
        (existing + invariant).forEach { current ->
            // Заменённое правило уходит в конец, а не остаётся на месте: последним видно то,
            // что человек объявил только что.
            merged.remove(textOf(current))
            merged[textOf(current)] = current
        }
        return merged.values.toList()
    }

    /** Место в списке: null — место есть, иначе причина отказа ([MAX_INVARIANTS]). */
    fun limitReason(count: Int): String? = TOO_MANY.takeIf { count > MAX_INVARIANTS }

    /**
     * Блок правил для системного сообщения: заголовок и по строке на правило.
     *
     * Заголовок говорит то, ради чего блок и уходит в модель: правила нарушать нельзя, и решение
     * обязано им соответствовать, — иначе список читается как пожелания, которые можно обойти.
     * Правило неизвестного вида в блок не попадает ([line]): подписи у него нет, а в списке
     * требований безымянная строка только мешает. Пусто — сообщения нет.
     */
    fun render(invariants: List<Invariant>): String {
        val lines = invariants.mapNotNull { line(it) }
        return if (lines.isEmpty()) "" else (listOf(INVARIANTS_HEADER) + lines).joinToString("\n")
    }

    /** Строка правила для блока промпта и лога; null — вид неизвестен, и подписи у правила нет. */
    fun line(invariant: Invariant): String? =
        InvariantKind.ofWire(invariant.kind)?.let { "- ${it.title}: ${invariant.value}" }

    /** По чему видно повтор: формулировка без регистра и внешних пробелов. */
    private fun textOf(invariant: Invariant): String = invariant.value.trim().lowercase()
}

/**
 * Отчёт по инвариантам в ответе агента: что ушло в запрос и чем закончилась проверка.
 *
 * Уезжает в отчёте ответа, как отчёты памяти и задачи, поэтому по нему — без отдельного
 * запроса — видно и блок правил в промпте, и причину отказа. Каталог видов в отчёт не входит:
 * он есть в снимке ([InvariantSnapshot.kinds]).
 *
 * Пустой отчёт — правил нет: человек убрал их все, и тогда ни блока, ни служебного вызова
 * не было, а поведение прежних дней не меняется.
 *
 * @param invariants Правила, которые ушли в запрос системным сообщением.
 * @param tokens Токены блока инвариантов и сообщения проверки.
 * @param verdict Вердикт проверки; null — проверки не было или её ответ не разобрался, и тогда
 *        правило отказа в запрос не добавлялось, а блок правил всё равно ушёл.
 * @param violated Виды нарушенных инвариантов: значение [InvariantKind.wire]; пусто, если
 *        проверка запрос разрешила.
 * @param reason Объяснение от проверки, чем именно запрос нарушает правила: причины нарушений
 *        в том же порядке, что и [violated].
 * @param updateTokens Токены служебного вызова проверки (запрос и ответ).
 * @param updateCostUsd Цена этого вызова в USD; null — тариф не опубликован.
 */
@Serializable
data class InvariantReport(
    @SerialName("invariants") val invariants: List<Invariant> = emptyList(),
    @SerialName("tokens") val tokens: Int = 0,
    @SerialName("verdict") val verdict: String? = null,
    @SerialName("violated") val violated: List<String> = emptyList(),
    @SerialName("reason") val reason: String? = null,
    @SerialName("update_tokens") val updateTokens: Int = 0,
    @SerialName("update_cost_usd") val updateCostUsd: Double? = null
)
