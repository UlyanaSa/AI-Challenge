package com.osvin.aichallenge.agent

import java.util.concurrent.ConcurrentHashMap

/**
 * Хранилище инвариантов профиля — отдельное от памяти и профиля, потому что правила проекта
 * приходят в диалог не из него ([Invariant]): их не извлекает модель и не переписывает
 * стратегия контекста, их объявляет человек и читает их агент.
 *
 * Состояний три, а не два, и различать их обязательно:
 *
 * - `null` — правил ещё не задавали, и в силе умолчание проекта ([Invariant.DEFAULT]);
 * - непустой список — правила, которые объявил человек;
 * - пустой список — правил нет: человек убрал их все. Тогда агент ни блока в промпт
 *   не подставляет, ни проверки не заводит.
 *
 * Свести пустой список к умолчанию нельзя: «правил нет» — это решение человека, а не
 * отсутствие решения, и подстановка умолчания молча вернула бы правила, которые он убрал.
 *
 * Ключ — профиль ([DEFAULT_PROFILE]): правила проекта одни на приложение, поэтому видны
 * из любого чата, как профиль и память. Сущность при этом своя: [MemoryStore] и
 * [ProfileStore] про инварианты ничего не знают.
 */
interface InvariantStore {

    /** Инварианты области; null — правил ещё не задавали, и в силе умолчание проекта. */
    fun get(profileId: String): List<Invariant>?

    /** Сохраняет правила области целиком: список и есть состояние, частичного обновления нет. */
    fun put(profileId: String, invariants: List<Invariant>)
}

/**
 * Инварианты в памяти процесса: годятся тестам и локальному прогону — правила задаются
 * явными действиями человека, а не накапливаются из диалога, поэтому собирать их заново
 * после перезапуска нечем.
 *
 * Кто подставляет серверу долговременное хранилище, решает сам сервер: [InvariantStore]
 * от этого не зависит — как и у профиля ([ProfileStore]).
 */
class InMemoryInvariantStore : InvariantStore {

    private val invariants = ConcurrentHashMap<String, List<Invariant>>()

    override fun get(profileId: String): List<Invariant>? = invariants[profileId]

    override fun put(profileId: String, invariants: List<Invariant>) {
        this.invariants[profileId] = invariants
    }
}

/**
 * Правила, с которыми работает агент: объявленные человеком, а до них — умолчание проекта.
 *
 * Здесь и только здесь умолчание подставляется вместо пустого ответа хранилища. И агент,
 * и явные действия человека ([InvariantWriter]) читают правила через него, поэтому «человек
 * убрал все правила» и «человек их ещё не задавал» не могут разойтись между чтением
 * и записью: запись идёт от того же списка, который ушёл бы в запрос.
 */
fun InvariantStore.invariantsOrDefault(profileId: String = DEFAULT_PROFILE): List<Invariant> =
    get(profileId) ?: Invariant.DEFAULT
