package com.osvin.aichallenge.agent

/**
 * Стратегия управления контекстом диалога: что из присланной клиентом истории
 * уходит в модель. Переключается настройкой запроса ([AgentOptions.strategy]).
 *
 * @param wire Значение стратегии в запросе клиента и в отчёте агента.
 * @param title Название для логов, отчёта и интерфейса.
 */
enum class ContextStrategy(val wire: String, val title: String) {

    /** Вся история как есть: ничего не теряется и ничего не экономится. */
    FULL("full", "вся история"),

    /**
     * Скользящее окно: в модель уходят последние [AgentOptions.windowMessages]
     * сообщений, всё старшее отбрасывается. Дешевле всего и ничего не помнит.
     */
    SLIDING_WINDOW("sliding_window", "скользящее окно"),

    /**
     * Память фактов: отдельный блок «ключ — значение» обновляется после каждого
     * сообщения пользователя, в запрос уходят факты и последние сообщения окна.
     */
    FACTS("facts", "память фактов"),

    /**
     * Ветки диалога: в модель уходит только путь активной ветки — общая часть
     * с родителем до точки ветвления плюс её собственные сообщения.
     */
    BRANCHES("branches", "ветки диалога"),

    /** Сжатие истории (день 9): старшие сообщения свёрнуты в сводку. */
    SUMMARY("summary", "сжатие в сводку");

    /** Отправляет ли стратегия только последние сообщения окна. */
    val usesWindow: Boolean get() = this == SLIDING_WINDOW || this == FACTS

    /** Держит ли стратегия состояние по сессии: сводку или факты. */
    val keepsState: Boolean get() = this == FACTS || this == SUMMARY

    companion object {
        /** Стратегия по значению из запроса; неизвестное значение — [SUMMARY] (поведение дня 9). */
        fun fromWire(value: String?): ContextStrategy =
            entries.firstOrNull { it.wire == value?.trim()?.lowercase() } ?: SUMMARY
    }
}
