package com.osvin.aichallenge.mcp.github

import java.nio.file.Path
import java.nio.file.Paths

/**
 * Настройки доступа к GitHub: куда ходить и где искать токен.
 *
 * Токена здесь нет — и это главное отличие от прежней настройки. Раньше он приходил из
 * окружения одним прыжком, и человеку, у которого доступ к GitHub уже есть на машине
 * (в связке ключей, у `gh`, у `git`), приходилось доставать его и переписывать руками.
 * Теперь токен ищет цепочка источников ([GitHubCredentials]), а настройка отвечает только
 * за то, что цепочке нужно знать: адрес API и путь к файлу токена, если человек его назвал.
 *
 * Отсюда и отсутствие проверки «токен задан»: спрашивать нечего — сервер поднимают и для
 * `--list-tools`, где GitHub не нужен вовсе, а отсутствие доступа перестало быть ошибкой
 * запуска и стало состоянием, о котором сервер отчитывается ([GitHubAccessReport]).
 *
 * @param apiBase Корень GitHub REST API; по умолчанию — публичный GitHub.
 * @param tokenFile Путь из [TOKEN_FILE_ENV] или null, если переменной нет: без неё цепочка
 *        файла по этому пути не смотрит вовсе, а не ищет его «наугад».
 */
data class GitHubConfig(val apiBase: String = DEFAULT_API_BASE, val tokenFile: Path? = null) {

    companion object {

        /**
         * Переменная окружения с токеном — первый и самый прямой источник.
         *
         * Имена переменных окружения живут только здесь: цепочка источников берёт их отсюда,
         * а не повторяет литералами, — иначе одна правда о том, какие переменные мы читаем,
         * разошлась бы по файлам, и сервер молча перестал бы видеть знакомую настройку.
         */
        const val TOKEN_ENV = "GITHUB_TOKEN"

        /**
         * Переменная окружения с путём к файлу токена.
         *
         * Нужна там, где токен лежит не в домашнем каталоге: у каждого свой путь, и угадывать
         * его сервер не должен. Пустая переменная — то же, что отсутствующая: путь из пустой
         * строки вёл бы в текущий каталог, то есть в случайное место.
         */
        const val TOKEN_FILE_ENV = "GITHUB_TOKEN_FILE"

        /** Переменная окружения с адресом API: проверки подменяют её подставным сервером. */
        const val API_BASE_ENV = "GITHUB_API_BASE"

        /** Публичный GitHub REST API — значение по умолчанию. */
        const val DEFAULT_API_BASE = "https://api.github.com"

        /**
         * Служба в связке ключей macOS, под которой лежит токен.
         *
         * `security find-generic-password -s ai-challenge-github -w` — команда, которой источник
         * достаёт значение. Имя службы наше, поэтому оно и закреплено здесь: человеку его
         * называют в подсказке, и оно не должно разойтись с тем, что читает код.
         */
        const val KEYCHAIN_SERVICE = "ai-challenge-github"

        /**
         * Переменная окружения с домашним каталогом — из неё строится путь по умолчанию.
         *
         * Переменная не наша, но читаем её мы (см. [homeDirectory]), поэтому имя живёт здесь
         * же, где и остальные: искать в коде литерал «HOME» было бы тем же расхождением, только
         * с другой стороны.
         */
        const val HOME_ENV = "HOME"

        /**
         * Файл токена по умолчанию — `<дом>/.config/ai-challenge/github.token`.
         *
         * Дом берётся из [HOME_ENV], а не из `user.home`, и это не придирка: `user.home` JVM
         * читает из системной записи пользователя и за `HOME` не следует, поэтому подменить
         * дом окружением было бы нельзя, — а подменить его нужно: проверке нужен
         * детерминированный «доступа нет» на машине, где файл уже лежит. На Windows `HOME`
         * обычно не задан, и там остаётся `user.home` — единственный доступный источник дома.
         *
         * @param home Домашний каталог; по умолчанию — тот, что видит это окружение.
         */
        fun defaultTokenFile(home: Path = homeDirectory()): Path = home
            .resolve(".config")
            .resolve("ai-challenge")
            .resolve("github.token")

        /**
         * Домашний каталог: `HOME`, а если его нет — `user.home`. Почему именно так, сказано
         * в [defaultTokenFile].
         *
         * @param env Чтение окружения; по умолчанию — окружение процесса. Параметр, а не прямой
         *        `System.getenv`, чтобы проверки задавали дом поддельным, не трогая процесс.
         */
        fun homeDirectory(env: (String) -> String? = System::getenv): Path =
            env(HOME_ENV)?.takeIf { it.isNotBlank() }?.let(Paths::get)
                ?: Paths.get(System.getProperty("user.home"))

        /**
         * Настройки из окружения процесса: сервер запускают командой, конфиг ему не пишут.
         *
         * Пустая переменная — то же, что отсутствующая: в конфиге клиента легко оказаться
         * `"GITHUB_TOKEN_FILE": ""`, и путь из пустой строки увёл бы цепочку не туда.
         */
        fun fromEnvironment(): GitHubConfig = GitHubConfig(
            apiBase = System.getenv(API_BASE_ENV)?.takeIf { it.isNotBlank() } ?: DEFAULT_API_BASE,
            tokenFile = System.getenv(TOKEN_FILE_ENV)?.takeIf { it.isNotBlank() }?.let(Paths::get)
        )
    }
}
