package com.osvin.aichallenge.mcp.github

/**
 * Источник данных GitHub — то, что нужно инструментам сервера и что подменяют проверки.
 *
 * Интерфейс, а не конкретный класс: обработчики инструментов не должны знать про HTTP, поэтому
 * они проверяются на подставном источнике — без сети и без GitHub. Настоящая реализация —
 * [GitHubApiImpl], а данные, которые инструменты получают, — это и есть [GitHubApi].
 *
 * Токена в интерфейсе нет: инструментам он не нужен ни в каком виде, его ищет реализация
 * ([GitHubCredentials]) и тратит на заголовок `Authorization`. Так значение токена не может
 * попасть ни в ответ инструмента, ни в текст ошибки — неоткуда.
 */
interface GitHubApi {

    /**
     * Все репозитории, доступные владельцу токена, в порядке, который вернул GitHub.
     *
     * @throws GitHubApiException Токена на машине нет, токен не принят, прав нет, GitHub ответил
     *         не-2xx или сеть недоступна: это ошибка вызова инструмента, а не повод уронить сервер.
     */
    suspend fun repositories(): List<GitHubRepository>

    /**
     * Один репозиторий владельца токена по короткому имени.
     *
     * Имя, а не полное `владелец/репозиторий`: владелец — это владелец токена, и он один
     * и тот же у [repositories]; спрашивать его у вызывающего значило бы заставлять модель
     * угадывать логин, которого она не знает.
     *
     * @throws GitHubApiException То же, что у [repositories]: см. её KDoc. Отдельный случай —
     *         код 404: репозитория с таким именем у владельца нет.
     */
    suspend fun repository(name: String): GitHubRepository

    /**
     * Последние коммиты репозитория владельца токена, свежие первыми, не больше [limit].
     *
     * @param limit Сколько коммитов вернуть; проверка границ — на стороне инструмента, здесь
     *        значение уходит в размер страницы GitHub как есть.
     * @throws GitHubApiException То же, что у [repositories]: см. её KDoc.
     */
    suspend fun commits(name: String, limit: Int): List<GitHubCommit>

    /**
     * Профиль владельца токена: кто вошёл и какие права у токена.
     *
     * @throws GitHubApiException То же, что у [repositories]: см. её KDoc.
     */
    suspend fun account(): GitHubAccount

    /**
     * Состояние доступа — то, чем отчитывается инструмент `github_access`.
     *
     * Разобранные причины отсутствия доступа исключением не выходят: «токена нет на машине»,
     * «токен не принят», «сеть недоступна» — это состояния, и они приходят в
     * [GitHubAccessReport.hint]. Так тому, кто отчитывается о доступе, не приходится ловить
     * исключение и собирать отчёт заново — то есть делать ту же работу в двух местах и разойтись
     * в том, что считать состоянием. Отличие от [repositories] и [account] именно в этом: там
     * отсутствие токена — ошибка вызова, здесь — ответ.
     *
     * Неожиданный сбой (например, ответ GitHub, который не разобрался) исключением как раз
     * выходит: поломку от состояния отличает вызывающий, и инструмент `github_access` делает
     * это сам, оставляя обещание «ошибкой не отвечаю» в силе.
     */
    suspend fun access(): GitHubAccessReport
}

/**
 * Владелец токена и его права.
 *
 * Отдельный тип, а не [GitHubAccessReport]: это то, что вернул GitHub, без ответа на вопрос
 * «стоит ли показывать кнопку подключения». Отчёт ([GitHubAccessReport]) собирается из профиля
 * и места, откуда взят токен, — и в нём же лежит случай, когда профиль спросить не удалось.
 *
 * @param login Логин владельца; null — GitHub логина не назвал.
 * @param scopes Права токена.
 * @param scopesReported GitHub сообщил права: у fine-grained токенов заголовка с правами нет
 *        вовсе, и «права не сообщены» нельзя показывать как «прав нет».
 */
data class GitHubAccount(val login: String?, val scopes: List<String>, val scopesReported: Boolean)

/**
 * Обращение к GitHub не удалось.
 *
 * Отдельный тип, а не общий `Exception`: инструмент показывает текст ошибки пользователю,
 * и «сеть недоступна» должно отличаться от опечатки в коде. [status] — код ответа HTTP,
 * null — до GitHub вообще не дошло (нет токена на машине или сеть не отвечает).
 */
class GitHubApiException(val status: Int?, message: String) : IllegalStateException(message)
