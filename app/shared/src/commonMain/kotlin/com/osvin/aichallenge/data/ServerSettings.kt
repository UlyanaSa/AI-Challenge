package com.osvin.aichallenge.data

import com.osvin.aichallenge.serverBaseUrl

/**
 * Куда уходит вопрос: сегодняшний путь агента или приватный сервис дня 30.
 *
 * Режим — часть настройки, а не отдельный флаг интерфейса, потому что от него зависит
 * и адрес, и наличие ключа, и то, кто ведёт историю: на пути `/v1` историю и сессии
 * держит агент, а у сервиса `/api/…` своя история в SQLite. Держать режим в экране
 * значило бы разойтись с тем, что уходит на провод: экран показывал бы один разговор,
 * а запрос уходил бы в другой.
 *
 * Значения на проводе у режимов нет: режим не уезжает на сервер — он выбирает,
 * кому именно адресован запрос, и на сервере оба пути живут независимо.
 */
enum class ChatMode { CURRENT, SERVICE }

/**
 * Чем закончилась проверка подключения к приватному сервису.
 *
 * Состояния перечисляют ровно те исходы, которые человек различает в шторке: служба
 * не отвечает ([UNAVAILABLE]), ключ не принят ([AUTH_ERROR]), служба ответила, но модели
 * на ней нет ([MODEL_MISSING]) — и всё в порядке ([CONNECTED]). Отдельного состояния
 * «ошибка вообще» нет намеренно: по нему нельзя решить, что править — адрес, ключ
 * или имя модели, — а именно это человек и пришёл выяснять.
 */
enum class ServerConnectionState { UNKNOWN, CHECKING, CONNECTED, AUTH_ERROR, UNAVAILABLE, MODEL_MISSING }

/**
 * Итог проверки подключения к приватному сервису: состояние словами и список моделей.
 *
 * Сообщение и список — часть отчёта, а не вывод шторки: причину отказа называет та,
 * кто проверяла (сеть, ключ, список моделей сервиса), и шторке остаётся её показать.
 * Собирать объяснение из кода ответа в интерфейсе значило бы держать вторую копию
 * правил, по которым сервис отказывает.
 *
 * @param state Исход проверки; [ServerConnectionState.UNKNOWN] — проверки ещё не было.
 * @param message Причина словами: «Подключён…», «Недоступен…», «Ошибка авторизации…».
 * @param models Имена моделей, которые сервис назвал; пусто — списка не получили.
 */
data class ConnectionReport(
    val state: ServerConnectionState = ServerConnectionState.UNKNOWN,
    val message: String = "Проверка подключения не выполнялась",
    val models: List<String> = emptyList()
)

/**
 * Настройки приватного сервиса `/api/…`, которые человек вводит в шторке «Сервер».
 *
 * Живут только в памяти сессии приложения: ни в код, ни в файл, ни в хранилище чатов
 * они не пишутся. Так решено из-за ключа доступа ([apiKey]): он открывает весь сервис,
 * и оставленный на устройстве, пережил бы выход из приложения — на диске телефона,
 * в резервной копии и в логах. Отсутствие ключа в источнике — то же решение с другой
 * стороны: ключ вводит человек, и вписанный в код он был бы у всех одинаковым.
 * Плата за это названа честно: после перезапуска приложения адрес и ключ вводят заново.
 *
 * Адрес ([baseUrl]) у сервиса свой, а не тот же, что у агента: сервис дня 30 поднимают
 * отдельно (по умолчанию на том же порту, но это его собственный адрес), и общий адрес
 * связал бы две поверхности, у которых разные хозяева.
 *
 * @param mode Режим чата: сегодняшний путь `/v1` или приватный сервис `/api/…`.
 * @param baseUrl Адрес сервиса без пути, например `http://10.0.2.2:8080`.
 * @param apiKey Ключ доступа: уходит заголовком `X-API-Key` только на домен сервиса.
 * @param model Имя модели, которое просят у сервиса; по умолчанию — модель дня 30.
 * @param temperature Температура генерации: перекрывает умолчание сервиса, но не потолки.
 * @param maxTokens Бюджет ответа в токенах; сервис обрежет его до своего потолка.
 * @param contextWindow Потолок контекстного окна; сервис обрежет его до своего потолка.
 */
data class ServerSettings(
    val mode: ChatMode = ChatMode.CURRENT,
    val baseUrl: String = serverBaseUrl(),
    val apiKey: String = "",
    val model: String = "qwen3:1.7b",
    val temperature: Double = 0.7,
    val maxTokens: Int = 512,
    val contextWindow: Int = 4096
)
