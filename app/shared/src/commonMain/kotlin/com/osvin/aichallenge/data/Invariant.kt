package com.osvin.aichallenge.data

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

/**
 * Инвариант проекта: правило, которое ассистент нарушать не имеет права —
 * архитектурное решение, ограничение стека или бизнес-правило.
 *
 * Это копия серверной модели, как и [MemoryRecord] рядом: инварианты лежат
 * на сервере отдельным хранилищем, а не в истории сообщений, и сервер подставляет
 * их в каждый запрос к модели системным сообщением. Клиент их только показывает
 * и правит явными действиями человека, поэтому на провод уходят те же поля.
 *
 * [kind] — вид правила на проводе (`architecture`, `decision`, `stack`, `business`),
 * а не название: подписи и пояснения видов приходят каталогом в снимке
 * ([InvariantKindInfo]), и своей таблицы видов у клиента нет — она разошлась бы
 * с серверной и молча пережила бы добавление нового вида.
 *
 * @param kind Вид правила на проводе.
 * @param value Формулировка правила: что именно нельзя нарушать.
 */
@Serializable
data class Invariant(
    @SerialName("kind") val kind: String,
    @SerialName("value") val value: String
)

/**
 * Вид инварианта из каталога сервера: [kind] — значение на проводе, [title] и [hint] —
 * подпись и пояснение вида. Каталог — единственное место, где клиент берёт название
 * вида, поэтому у шторки инвариантов нет своей таблицы названий.
 *
 * @param kind Значение вида для записи и удаления правила.
 * @param title Название вида для чипа и раздела шторки.
 * @param hint Пояснение вида: что за правила в него пишут.
 */
@Serializable
data class InvariantKindInfo(
    @SerialName("kind") val kind: String,
    @SerialName("title") val title: String,
    @SerialName("hint") val hint: String
)

/**
 * Снимок инвариантов профиля: сами правила и каталог видов. Тем же ответом сервер
 * отвечает и на чтение, и на добавление, и на удаление правила, поэтому состояние
 * шторки всегда берётся из ответа сервера, а не собирается на клиенте.
 *
 * Умолчаний здесь нет намеренно: правила этого проекта и подстановка умолчаний, когда
 * человек их ещё не задавал, живут на сервере. Вторая копия умолчания на клиенте
 * разошлась бы с серверной, поэтому пустой список — это «правил нет», а не «список
 * ещё не пришёл».
 *
 * @param invariants Правила профиля: что лежит в хранилище инвариантов сейчас.
 * @param kinds Каталог видов: порядок разделов шторки и их подписи.
 */
@Serializable
data class InvariantSnapshot(
    @SerialName("invariants") val invariants: List<Invariant> = emptyList(),
    @SerialName("kinds") val kinds: List<InvariantKindInfo> = emptyList()
)

/**
 * Явное добавление инварианта: [kind] и [value] уезжают на сервер как есть. Профиля
 * в записи нет: правила принадлежат профилю по умолчанию, как память и профиль,
 * и видны из любого чата — адресовать правило чату нечем и незачем.
 */
@Serializable
data class InvariantWriteRequest(
    @SerialName("kind") val kind: String,
    @SerialName("value") val value: String
)
