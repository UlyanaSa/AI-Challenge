package com.osvin.aichallenge.data

/**
 * Стратегия управления контекстом диалога: что из истории уходит в модель.
 * Выбирается в шторке настроек и уезжает на сервер полем `strategy` запроса;
 * сервер понимает те же значения, что агент (день 10).
 *
 * @param wire Значение стратегии в запросе к серверу и в отчёте агента.
 * @param title Название для интерфейса и лога.
 * @param hint Пояснение одной строкой — что стратегия делает с историей диалога.
 */
enum class ContextStrategy(val wire: String, val title: String, val hint: String) {

    /** Вся история как есть: ничего не теряется и ничего не экономится. */
    FULL(
        wire = "full",
        title = "Вся история",
        hint = "В модель уходит весь диалог целиком"
    ),

    /**
     * Скользящее окно: в модель уходят последние [GenerationSettings.windowMessages]
     * сообщений, всё старшее отбрасывается.
     */
    SLIDING_WINDOW(
        wire = "sliding_window",
        title = "Скользящее окно",
        hint = "В модель уходят только последние сообщения: дешевле всего, но старое забывается"
    ),

    /**
     * Память фактов: важное из диалога копится списком «ключ — значение»
     * и переживает отброшенные сообщения.
     */
    FACTS(
        wire = "facts",
        title = "Память фактов",
        hint = "Важное копится в списке «ключ — значение» и переживает отброшенные сообщения"
    ),

    /** Ветки диалога: в модель уходит только путь активной ветки. */
    BRANCHES(
        wire = "branches",
        title = "Ветки диалога",
        hint = "Диалог ветвится от любого сообщения: в модель уходит только путь активной ветки"
    ),

    /** Сжатие истории (день 9): старшие сообщения свёрнуты в сводку. */
    SUMMARY(
        wire = "summary",
        title = "Сжатие в сводку",
        hint = "Старшие сообщения свёрнуты в сводку — поведение дней до 10"
    );

    /** Отправляет ли стратегия только последние сообщения окна. */
    val usesWindow: Boolean get() = this == SLIDING_WINDOW || this == FACTS

    companion object {
        /** Стратегия по умолчанию: пока в настройках не выбрали другую — как в дне 9. */
        val DEFAULT = SUMMARY

        /** Стратегия по значению из отчёта агента; неизвестное значение — [DEFAULT]. */
        fun fromWire(value: String?): ContextStrategy =
            entries.firstOrNull { it.wire == value?.trim()?.lowercase() } ?: DEFAULT
    }
}
