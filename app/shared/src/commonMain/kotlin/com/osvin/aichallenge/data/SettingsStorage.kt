package com.osvin.aichallenge.data

/**
 * Хранилище настроек на устройстве: имя настройки — строка, и больше ничего.
 *
 * Настройки сервиса ([ServerSettings]) переживают перезапуск приложения только тогда,
 * когда их есть куда положить. До этого они жили в памяти сессии, и после обновления
 * страницы человек видел пустое приложение: режим «Сервис» сбрасывался в локальный,
 * ключ пропадал, а чаты сервиса — живые, лежащие в его SQLite, — не подгружались, потому
 * что спрашивать о них стало некому. Поэтому настройки хранятся: на веб-таргете —
 * в `localStorage` браузера, на Android — в `SharedPreferences` (их подставляет точка
 * входа, как и хранилище чатов на Room).
 *
 * Форма «имя → строка» выбрана намеренно: значений семь, все они текстовые или сводятся
 * к тексту, и сериализатор ради них завёл бы второй формат хранения рядом с тем, что уже
 * есть у хранилища чатов. Числа пишутся текстом и разбираются обратно тем же кодом,
 * что читает их из шторки, — второй способ разбора разошёлся бы с первым.
 *
 * Пустое значение читается как «настройки нет»: ключ, адрес и имя модели пустыми
 * не бывают, и различать «пустая строка» и «поля нет» здесь нечего.
 */
interface SettingsStorage {

    /** Значение настройки; null — настройку не сохраняли. */
    fun read(key: String): String?

    /** Запоминает настройку; `null` — забывает её. */
    fun write(key: String, value: String?)
}

/**
 * Хранилище в памяти процесса: настройки не переживают перезапуск.
 *
 * Используется там, где своего хранилища нет (тесты, превью) — и по умолчанию
 * в репозитории, чтобы проверки ничего не писали на диск машины.
 */
class InMemorySettingsStorage : SettingsStorage {

    private val values = mutableMapOf<String, String>()

    override fun read(key: String): String? = values[key]

    override fun write(key: String, value: String?) {
        if (value == null) values.remove(key) else values[key] = value
    }
}
