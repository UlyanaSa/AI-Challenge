package com.osvin.aichallenge.data

/**
 * Закреплённый чат курсов валют — единственный чат, который приложение ведёт само.
 *
 * Это лента, а не диалог: строки в неё печатает монитор по расписанию ролью
 * [MessageRole.MONITOR], человек их не пишет, и модель их не получает. Поэтому
 * у чата постоянный идентификатор: перезапуск приложения находит тот же чат
 * и продолжает ту же ленту, а не заводит вторую. Идентификатор намеренно не
 * выглядит как сгенерированный (у обычных чатов это 32 hex-символа), — по нему
 * видно, что чат служебный. Если бы идентификатор был случайным, каждый запуск
 * приложения плодил бы новый чат со своей лентой, и хранилище заполнялось бы
 * пустыми чатами курсов.
 *
 * Заголовок тоже постоянный и лежит здесь, а не берётся из первого сообщения:
 * первого сообщения пользователя у этой ленты не будет никогда, а заголовок
 * в списке чатов нужен сразу, ещё до первого удара монитора.
 */
object CurrencyChat {
    /** Идентификатор чата; он же — идентификатор его сессии на сервере. */
    const val ID = "currency-monitor"

    /** Заголовок чата: в списке чатов и на верхней панели. */
    const val TITLE = "Курсы валют"
}
