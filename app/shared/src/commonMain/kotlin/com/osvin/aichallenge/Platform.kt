package com.osvin.aichallenge

interface Platform {
    val name: String
}

expect fun getPlatform(): Platform

/**
 * Адрес сервера агента для текущей платформы.
 *
 * Android-эмулятор видит хост-машину по адресу 10.0.2.2, браузер и десктоп —
 * по localhost, поэтому адрес задаётся платформой, а не общим кодом.
 */
expect fun serverBaseUrl(): String

/**
 * Текущее время в миллисекундах от начала эпохи (Unix epoch).
 *
 * Общий код не может знать платформенные часы: `System.currentTimeMillis()`
 * существует только на JVM, а iOS и браузер дают время из своих источников.
 * Платформенные реализации возвращают одну и ту же величину — миллисекунды
 * epoch, — поэтому отметки времени чатов и сообщений сопоставимы между
 * таргетами, а не сдвинуты относительно друг друга.
 */
expect fun nowMillis(): Long

/**
 * Адрес приложения у текущей платформы: `<origin><path>` у браузера, null — у остальных.
 *
 * Из него собирается ссылка «поделиться чатом» (§5): свежий чат живёт на сервисе, и второй
 * клиент открывает тот же разговор, если знает и адрес приложения, и идентификатор чата.
 * Не браузер своего адреса не знает — приложение запускают не по ссылке, и выдумывать
 * за него адрес значило бы дать человеку ссылку, которая никуда не ведёт.
 */
expect fun appAddress(): String?

/**
 * Идентификатор чата, с которым приложение открыли по ссылке: `?chat=<id>`.
 *
 * Читается при старте веб-таргета (§5) — по ссылке второго клиента открывается тот же
 * сервисный чат. Не браузер параметров адреса не имеет, поэтому там null.
 */
expect fun openedChatId(): String?

/**
 * Класть текст в буфер обмена платформы; false — буфера нет или он недоступен.
 *
 * Признак возвращается наружу, а не глотается: там, где буфера нет, ссылку всё равно
 * показывают — но текстом, который можно выделить, и без обещания «скопировано».
 */
expect fun copyToClipboard(text: String): Boolean

/** Имя параметра адреса, которым делятся чатом: `<адрес>/?chat=<id>` (§5). */
const val CHAT_QUERY_PARAM = "chat"

/**
 * Идентификатор чата из адреса: `?chat=<id>`.
 *
 * Разбор общий, а не платформенный: и адрес страницы, и ссылка из строки приходят
 * текстом, а проверяется разбор без сети. Первый параметр с этим именем и побеждает —
 * ссылку собирает клиент, и повторов в ней быть не должно; пустое значение считается
 * отсутствием параметра, иначе пустой `?chat=` открывал бы чат с пустым идентификатором.
 */
fun chatIdFromUrl(url: String?): String? =
    url?.substringAfter('?', "")
        ?.split('&')
        ?.firstOrNull { it.substringBefore('=') == CHAT_QUERY_PARAM }
        ?.substringAfter('=', "")
        ?.takeIf { it.isNotBlank() }
