package com.osvin.aichallenge.report.mcp

/**
 * Отказ по входу инструмента: аргумент не назван, назван недопустимо или разобрать его нечем.
 *
 * Исключением, а не значением, потому что причина одна на оба инструмента и на все их ветки
 * проверки: тип превращает её в `isError` в теле инструмента, а сами проверки бросают — иначе
 * каждая ветка решала бы заново, что вернуть. Наружу тип не выходит: клиент получает текст
 * причины полем результата, как и требует протокол.
 *
 * Разбор секций брошенным исключением, а не `null`: у «не разобрано» и «не назван заголовок»
 * разные причины, и модель должна увидеть ту, которая случилась, а не общее «неверный аргумент».
 *
 * @param message Что именно не так с вызовом — это уезжает модели словами.
 */
class ReportInputException(message: String) : Exception(message)
