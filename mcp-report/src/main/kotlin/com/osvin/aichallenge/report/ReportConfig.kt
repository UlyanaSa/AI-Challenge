package com.osvin.aichallenge.report

import java.nio.file.Path
import java.nio.file.Paths

/**
 * Настройки сервера отчётов: куда писать файлы.
 *
 * Каталог у сервера свой ([REPORTS_DIR_ENV]), а не общий с пайплайном: два сервера пишут разные
 * вещи, и общий каталог смешал бы отчёты по курсам с отчётами по материалу — а по имени файла
 * потом не отличить, кто его положил. Разные переменные означают и то, что серверы можно направить
 * в разные места, не переписывая ни одного из них.
 *
 * Путь читается здесь один раз и целиком: `Path` из окружения, а не строка, чтобы «где писать»
 * решалось в одном месте, а инструмент не разбирал переменные окружения в момент вызова.
 *
 * @param reportsDir Каталог, в который пишет `saveReport`. Создаётся записью, а не запуском.
 */
data class ReportConfig(val reportsDir: Path) {

    companion object {
        /** Переменная окружения с каталогом отчётов. */
        const val REPORTS_DIR_ENV = "REPORTS_DIR"

        /**
         * Каталог отчётов по умолчанию: `reports` рядом с процессом.
         *
         * Относительным путём, а не в домашнем каталоге: запуск из чужого каталога не должен
         * разбрасывать файлы по машине. Без создания каталога здесь: каталог заводит запись
         * (`saveReport`), и пустой каталог от одного лишь запуска сервера был бы мусором рядом
         * с процессом.
         */
        const val DEFAULT_REPORTS_DIR = "reports"

        /**
         * Настройки из окружения: пустая переменная — то же, что её отсутствие.
         *
         * Окружение — параметром, а не чтением внутри: так настройку можно задать в проверке,
         * не трогая переменные процесса, и «пустая строка вместо каталога» проверяется явно.
         */
        fun fromEnvironment(env: Map<String, String> = System.getenv()): ReportConfig = ReportConfig(
            reportsDir = env[REPORTS_DIR_ENV]?.takeIf { it.isNotBlank() }
                ?.let { Paths.get(it).toAbsolutePath() }
                ?: Paths.get(DEFAULT_REPORTS_DIR).toAbsolutePath()
        )
    }
}
