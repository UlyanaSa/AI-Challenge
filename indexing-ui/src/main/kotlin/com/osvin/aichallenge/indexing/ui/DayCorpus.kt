package com.osvin.aichallenge.indexing.ui

/**
 * Встроенный корпус дня: PDF, по которому собран эталонный вопрос.
 *
 * Вопрос дня задан заранее, и заранее же известно, где в этом PDF лежит ответ ([DayReference.pages]).
 * Поэтому корпус дня — сам файл, а не копия его текста: страницы, заголовки и абзацы извлекаются из
 * вёрстки при первом запуске, и эталон не может разойтись с данными, потому что данных, кроме PDF,
 * нет. Копия текста в проекте означала бы вторую версию книги, которую нужно держать в согласии
 * с первой.
 *
 * Из всего файла индексируется только [PAGES]: ответ лежит внутри этого отрезка, а остальные
 * страницы вопроса не касаются — индексировать их значило бы искать ответ там, где его нет,
 * и разбавлять выдачу посторонним текстом. Ограничение стоит на входе, в самом разборе PDF, поэтому
 * за его пределами не оказывается ни текста, ни заголовков, а номера страниц внутри корпуса
 * остаются физическими страницами файла: на них и ссылается эталон.
 *
 * Сам файл в репозиторий не попадает (авторское право, `.gitignore`). Если его нет рядом с кодом,
 * [bytes] возвращает `null`: страница тогда работает только с документами, которые загрузил человек,
 * и говорит об этом при запуске, а не притворяется, что корпус дня есть.
 */
object DayCorpus {

    /** Путь ресурса на классовом пути модуля. Файл лежит в `src/main/resources`. */
    const val RESOURCE: String = "/book.pdf"

    /**
     * Имя файла корпуса дня в рабочем каталоге страницы.
     *
     * Своё имя, а не имя PDF: корпус — это текст, извлечённый из PDF, и расширение у него `.md`.
     * Имя совпадает с тем, что дал бы разбор загруженного файла ([PdfSource]), и по нему страница
     * отличает документ дня от всего, что загрузил человек.
     */
    const val FILE_NAME: String = "book.md"

    /**
     * Страницы PDF, которые входят в корпус дня.
     *
     * Отрезок выбран вокруг ответа на вопрос дня ([DayReference.pages]): сюда попадает начало романа
     * и история Степана Трофимовича — то есть и ответ, и соседний с ним текст, который поиск видит
     * как похожий. Всю книгу индексировать для этого не нужно.
     */
    val PAGES: IntRange = 1..40

    /** Байты ресурса или `null`, если файла рядом с кодом нет. */
    fun bytes(): ByteArray? =
        DayCorpus::class.java.getResourceAsStream(RESOURCE)?.use { it.readBytes() }
}
