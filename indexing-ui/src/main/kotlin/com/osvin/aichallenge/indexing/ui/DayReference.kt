package com.osvin.aichallenge.indexing.ui

import com.osvin.aichallenge.indexing.model.Document
import com.osvin.aichallenge.indexing.model.DocumentFile

/**
 * Эталон дня: вопрос, ответ на него и страницы, где этот ответ лежит.
 *
 * Вопрос и ответ — часть задания, и обе формулировки заданы заранее: страница ищет именно этот
 * вопрос и сверяет найденное именно с этим ответом. Книга дня — «Бесы» Ф. М. Достоевского, корпус
 * дня кончается на сороковой странице, а ответ лежит в самом его начале, в первой главе
 * («Вместо введения»), в истории Степана Трофимовича Верховенского. Книга говорит об этом прямо:
 * «настоящею причиной перемены карьеры было еще прежнее и снова возобновившееся деликатнейшее
 * предложение ему от Варвары Петровны Ставрогиной… принять на себя воспитание и всё умственное
 * развитие ее единственного сына» (стр. 7–8), и рядом называет причину согласия — именьице,
 * приходившееся «совершенно рядом со Скворешниками».
 *
 * Эталон задан двумя страницами, а не одной: предложение о воспитании разорвано вёрсткой —
 * на стр. 7 оно доходит до «принять на», а «себя воспитание…» продолжается уже на стр. 8.
 * Диапазон покрывает и предложение, и причину принятого места, то есть весь отрывок, о котором
 * говорит ответ задания. То же приглашение названо ещё раз, в главе второй (стр. 25: «Для него-то
 * и приглашен был Степан Трофимович в воспитатели»), но там речь о сыне Варвары Петровны как
 * о лице, а не о причине; чанк со стр. 25 идёт вторым-третьим в обеих выдачах, потому что слова
 * в нём те же, — но «почему» сказано на стр. 7–8, и эталон задан ими.
 *
 * Ранжирование от эталона не зависит, и на этой книге видно, чем меры различаются. У модели
 * эталонные чанки первые в обеих стратегиях: фиксированная начинает со стр. 8 (0.649) и держит
 * следом стр. 7–8 (0.636), структурная — со стр. 8 (0.651); у хеширования те же чанки восьмой
 * и девятый (0.324 и 0.301), а наверх выходит стр. 17, где о сыне Степана Трофимовича сказано
 * лишь то, что он видел его дважды. Лексическая мера отвечает на вопрос «где эти слова есть»,
 * модель — «где об этом сказано», и вопрос, сформулированный не словами книги, показывает разницу
 * прямо. Эталон от ранга не страдает: страницы ответа, ответ задания и текст страниц показаны
 * на странице отдельно и всегда, — это и есть решение: ответ должен быть виден, даже когда поиск
 * ушёл на соседние страницы.
 *
 * Ответ задания хранится здесь потому, что он и есть условие задачи: формулировка не выводится
 * из корпуса, и без неё поиск было бы не с чем сверять. Текст самих страниц по-прежнему не
 * хранится: он читается из документа дня ([Pages.text]), поэтому место ответа не может разойтись
 * с данными — здесь указано, где читать, а не что там написано.
 *
 * Эталон задан страницами PDF, а не файлом с разделом, потому что корпус страницы — это PDF,
 * который загружает человек: имя файла у каждого своё, а нумерация страниц — свойство самого PDF.
 * Страницы 7 и 8 — физические страницы PDF дня, и обе входят в его корпус ([DayCorpus.PAGES]).
 * Если таких страниц в корпусе нет, эталон к нему не относится, и страница говорит об этом прямо,
 * а не подставляет чужой текст.
 */
object DayReference {

    /** Вопрос дня: сформулирован словами задания, а не словами книги. */
    const val QUESTION: String = "Почему Степан Трофимович стал воспитателем сына Варвары Петровны?"

    /**
     * Ответ задания на вопрос дня.
     *
     * Поиск ищет чанк, ближайший к вопросу, а этот текст — то, что человек должен в найденном
     * прочитать. Разбор близости у каждого результата показывает, по каким словам близость
     * посчитана и насколько они далеки от ответа задания.
     */
    const val ANSWER: String =
        "После перемен в своей карьере Степан Трофимович принял предложение Варвары Петровны " +
            "заняться воспитанием и умственным развитием её единственного сына."

    /** Страницы документа дня, на которых лежит ответ: предложение о воспитании и его причины. */
    val pages: IntRange = 7..8
}

/**
 * Текст заданных страниц из документов прогона.
 *
 * Границы берутся у карты страниц файла ([com.osvin.aichallenge.indexing.model.PageMark]): текст
 * от начала первой нужной страницы до начала первой страницы за диапазоном. Так текст читается
 * из документа, а не из индекса: если бы эталон собирался из чанков, оценка попадания измеряла бы
 * согласие стратегии с самой собой.
 */
object Pages {

    /** Текст страниц [pages] из всех файлов [documents], где такие страницы есть. */
    fun text(documents: List<Document>, pages: IntRange): String {
        val parts = documents.asSequence()
            .flatMap { it.files }
            .mapNotNull { file -> slice(file, pages) }
            .toList()
        return parts.joinToString("\n\n")
    }

    private fun slice(file: DocumentFile, pages: IntRange): String? {
        val from = file.pages.firstOrNull { it.page in pages }?.offset ?: return null
        // Страницы идут по возрастанию смещения, поэтому первая страница за диапазоном и есть конец.
        val to = file.pages.firstOrNull { it.page > pages.last }?.offset ?: file.content.length
        if (to <= from) return null
        return file.content.substring(from, to).trim().ifEmpty { null }
    }
}
