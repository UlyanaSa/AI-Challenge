package com.osvin.aichallenge.service

/**
 * Сессия чата: единица хранения истории.
 *
 * Идентификатор — единственное, что клиент называет сам при каждом запросе: имя сессии
 * человек видит в списке, но адресуется диалог идентификатором, потому что имя может
 * повториться, а идентификатор — нет, и по нему же сервис отличает своих клиентов
 * друг от друга (чужой идентификатор в ответе 404, а не пустая история).
 *
 * @param id Идентификатор сессии: 32 шестнадцатеричных символа.
 * @param title Имя сессии для списка: пустое не хранится, вместо него подставляется
 *        [DEFAULT_TITLE] — сервис не отказывает в создании чата из-за отсутствия имени.
 * @param createdAt Момент создания в миллисекундах эпохи.
 * @param updatedAt Момент последнего сообщения: по нему сессии упорядочиваются в списке,
 *        чтобы свежий диалог был первым, а не тот, который дольше всех не трогали.
 * @param previousChatId Сессия, диалог которой сжат в [summary]; `null` — сводки нет.
 * @param summary Сводка прошлого диалога: сервис передаёт её модели отдельной частью
 *        системной инструкции. Пустая строка не хранится — «сводки нет» выражается `null`.
 * @param summaryMessages Сколько сообщений прошлого чата сжато в [summary]; `0` — сводки нет.
 * @param messageCount Сколько сообщений лежит в самой сессии. Заполняется только там, где число
 *        нужно (списку чатов), — чтение одной сессии его не считает и оставляет нулём: лишний
 *        подзапрос на каждый ответ модели был бы платой ни за что.
 */
data class ChatSession(
    val id: String,
    val title: String,
    val createdAt: Long,
    val updatedAt: Long,
    val previousChatId: String? = null,
    val summary: String? = null,
    val summaryMessages: Int = 0,
    val messageCount: Int = 0
) {
    companion object {

        /** Имя сессии по умолчанию: запрос без имени создаёт чат, а не отказ. */
        const val DEFAULT_TITLE = "Новый чат"
    }
}

/**
 * Сообщение диалога, как оно лежит в хранилище.
 *
 * Той же формы, что и [com.osvin.aichallenge.models.ChatMessage] у транспорта, но без
 * полей вызовов инструментов: у сервиса нет ни инструментов, ни веток диалога — модель
 * отвечает текстом, и хранить нечего. Сводить типы в один не стали: у сообщения модели
 * в запросе есть поля, которых в хранилище не бывает, и общий тип заставлял бы хранилище
 * знать о них.
 *
 * @param role Роль автора: `user` или `assistant` (системных сообщений в истории нет —
 *        обязательная инструкция сервиса живёт в настройках, а не в диалоге).
 * @param content Текст сообщения.
 * @param createdAt Момент записи в миллисекундах эпохи: порядок сообщений в сессии.
 */
data class StoredMessage(val role: String, val content: String, val createdAt: Long)

/**
 * Размеры хранилища для метрик.
 *
 * @param sessions Сколько сессий заведено.
 * @param messages Сколько сообщений лежит во всех сессиях.
 */
data class StoreCounts(val sessions: Int, val messages: Int)

/**
 * Хранилище сессий и истории чата.
 *
 * Интерфейс нужен ради одной развязки: маршруты сервиса проверяются без базы, а база —
 * без HTTP. Тесты маршрутов подставляют свою реализацию, поэтому ни один из них не
 * зависит от файла, а тесты хранилища не поднимают сервер.
 *
 * Методы синхронные и блокирующие: SQLite через JDBC асинхронным не бывает, а притворяться
 * им хуже, чем назвать как есть, — вызывающий сам решает, каким диспетчером увести вызов
 * из общего пула ([kotlinx.coroutines.Dispatchers.IO] на стороне маршрута).
 */
interface ChatSessionStore : AutoCloseable {

    /**
     * Заводит сессию.
     *
     * @param title Имя сессии; `null` или пустое — [ChatSession.DEFAULT_TITLE].
     * @param nowMillis Момент создания: приходит параметром, а не берётся из часов внутри,
     *        чтобы тест проверял порядок сообщений, не ожидая реального времени.
     */
    fun create(title: String?, nowMillis: Long): ChatSession

    /** Сессия по идентификатору; `null` — такой сессии нет. */
    fun find(id: String): ChatSession?

    /**
     * Дописывает сообщение в конец сессии и обновляет её время.
     *
     * Возвращает записанное сообщение; вызывающий не проверяет существование сессии
     * повторно — он уже сделал это в [find], а гонка двух запросов к одной сессии
     * разводится мьютексом на сессию в маршруте.
     */
    fun append(chatId: String, role: String, content: String, nowMillis: Long): StoredMessage

    /** Все сообщения сессии в порядке записи; неизвестная сессия — пустой список. */
    fun messages(chatId: String): List<StoredMessage>

    /**
     * Чаты для списка: свежие сверху, у каждого — число сообщений и сводка.
     *
     * @param limit Потолок числа чатов в ответе: он уже обрезан настройкой сервиса, поэтому
     *        хранилище не пересчитывает его второй раз.
     */
    fun list(limit: Int): List<ChatSession>

    /**
     * Самая свежая сессия, кроме указанной, у которой есть хотя бы одно сообщение.
     *
     * Метод существует ради сводки: сворачивать пустой диалог не из чего, а новая сессия
     * к моменту поиска ещё не заведена — [excluding] остаётся страховкой от выбора чата
     * самим собой, если вызывающий уже держит идентификатор.
     *
     * @param excluding Идентификатор, который не может стать прошлым чатом.
     * @return Сессия или `null`, если подходящей нет: «сворачивать нечего» — не отказ.
     */
    fun latestWithMessages(excluding: String): ChatSession?

    /**
     * Дописывает сводку и её источник к уже созданной сессии.
     *
     * Отдельно от [create], потому что сводка строится уже после того, как чат заведён:
     * отказ модели не должен отменять создание, а писатель сводки обязан быть один —
     * тот, кто её построил.
     *
     * @param chatId Сессия, которой приписывается сводка.
     * @param previousChatId Чат — источник сводки; `null` — источника нет.
     * @param summary Текст сводки; `null` — сводку построить не удалось.
     * @param messages Сколько сообщений источника в неё сжато.
     */
    fun setSummary(chatId: String, previousChatId: String?, summary: String?, messages: Int)

    /**
     * Удаляет сессию вместе с историей.
     *
     * @return Сколько сообщений удалено; `-1` — сессии не было. Число, а не флаг: клиенту
     *         показывается, что именно убрано, а `-1` отличается от «была пустая сессия».
     */
    fun delete(chatId: String): Int

    /** Размеры хранилища: сессии и сообщения. */
    fun counts(): StoreCounts
}
