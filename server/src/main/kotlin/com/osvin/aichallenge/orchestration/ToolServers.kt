package com.osvin.aichallenge.orchestration

/**
 * Имена серверов инструментов: по ним строится имя вызова и находится маршрут.
 *
 * Константы, а не строки на местах: имя сервера стоит в имени вызова, которое видит модель
 * (`report.saveReport`), и в строках протокола. Опечатка в одном месте дала бы вызов, который
 * не находит сервер, — а искали бы её по логу, а не по компилятору.
 */
object ToolServers {

    /** Сервер GitHub: репозитории и коммиты. */
    const val GITHUB = "github"

    /** Служба курсов: история и сводки. */
    const val CURRENCY = "currency"

    /** Пайплайн дня 19: курсы, сводка, запись файла. */
    const val PIPELINE = "pipeline"

    /** Сервер отчётов дня 20: сборка markdown и запись файла. */
    const val REPORT = "report"
}
