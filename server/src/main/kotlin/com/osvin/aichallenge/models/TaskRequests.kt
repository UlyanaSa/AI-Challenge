package com.osvin.aichallenge.models

import kotlinx.serialization.Serializable

/**
 * Взятие задачи в работу: пользователь сам заводит её в этом диалоге.
 *
 * Явное действие человека, как запись в память: пока задачи нет, агент её не ведёт
 * и к модели за состоянием не ходит. Сессия в теле обязательна, потому что состояние
 * задачи, в отличие от памяти, принадлежит диалогу, а не профилю: этап и шаг описывают
 * конкретную работу в конкретном чате, и без [sessionId] у запроса нет адреса.
 *
 * @param sessionId Идентификатор диалога, в котором заводится задача.
 */
@Serializable
data class TaskStartRequest(
    val sessionId: String
)

/**
 * Пауза и продолжение задачи: сессию называет тело, действие — значение [paused].
 *
 * Одно поле на оба действия, потому что разница между ними только в нём: на паузе
 * состояние заморожено, шаг и ожидаемое действие остаются на месте, и после снятия
 * паузы модель видит тот же шаг — пересказывать выполненное не надо.
 *
 * @param sessionId Идентификатор диалога, в котором ведётся задача.
 * @param paused true — поставить на паузу, false — продолжить с того же шага.
 */
@Serializable
data class TaskPauseRequest(
    val sessionId: String,
    val paused: Boolean
)
