package com.osvin.aichallenge.models

import kotlinx.serialization.Serializable

/**
 * Явная правка инвариантов: человек сам называет вид правила и его формулировку.
 *
 * Тело одно на добавление и на удаление, потому что действие называет метод, а не
 * содержимое: правило адресуется видом и текстом, а запоминается оно или забывается —
 * решает маршрут (`POST` или `DELETE`).
 *
 * Оба поля необязательны на проводе намеренно: вид и формулировку проверяет код
 * ([com.osvin.aichallenge.agent.InvariantRules.normalize]), и присланная половина
 * правила — обычный отказ с причиной (400), а не сбой разбора тела, после которого
 * клиент получил бы «ошибку сервера» вместо объяснения.
 *
 * Профиля в теле нет: инварианты лежат по профилю сервера, а не приходят от клиента —
 * иначе правило подставлял бы клиент, а проверять его должен сервер.
 *
 * @param kind Вид инварианта: значение `InvariantKind.wire`.
 * @param value Формулировка правила: одна фраза, до 300 символов.
 */
@Serializable
data class InvariantWriteRequest(
    val kind: String? = null,
    val value: String? = null
)
