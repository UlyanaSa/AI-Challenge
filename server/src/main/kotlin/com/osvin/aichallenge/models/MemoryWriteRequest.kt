package com.osvin.aichallenge.models

import kotlinx.serialization.Serializable

/**
 * Явная запись в память: пользователь сам решает, что сохранить и в каком типе памяти.
 *
 * Тип памяти называется так же, как в задании дня (`short_term`, `working`, `long_term`),
 * и приходит с провода как есть. Код проверяет, что тип известен и что в него можно
 * писать: краткосрочная память — это сообщения диалога, её пишет сам чат.
 *
 * Сессии у записи нет: оба писаемых типа живут по профилю, а не по чату, поэтому
 * запись видна из любого чата. Рабочую память задачи от долговременной отличает
 * срок жизни, а не область: она лежит в памяти сервера и обнуляется его перезапуском.
 *
 * @param layer Тип памяти: значение `MemoryLayer.wire`.
 * @param value Текст записи: одна фраза, до 200 символов.
 */
@Serializable
data class MemoryWriteRequest(
    val layer: String,
    val value: String
)
