package com.osvin.aichallenge.currency

import java.math.BigDecimal
import java.time.Instant

/**
 * Курс одной единицы валюты в рублях на момент получения.
 *
 * [rateToRub] — цена именно одной единицы, а не того номинала, которым её называет поставщик:
 * у ЦБ курс приходит с полем `Nominal` (для евро, доллара и лари это 1, но для иены — 100),
 * и деление на номинал делает поставщик, а не читатель. Иначе один и тот же курс значил бы
 * разное в истории, в сводке и в ответе инструмента, а номинал пришлось бы тащить через все
 * слои — до агента, которому он не нужен.
 *
 * [receivedAt] — когда значение получено сервисом, а не на какую дату его назначил поставщик.
 * История отвечает на вопрос «что было известно в этот час», поэтому точка отсчёта — момент
 * получения; у ЦБ своя дата публикации (курс на следующий день, по выходным не меняется),
 * и она в историю не помещается: два разных вопроса — «когда мы это узнали» и «на когда это
 * назначено». Момент округляется до секунды, чтобы записи одного обновления сортировались
 * одинаково и в базе (там время хранится текстом), и в памяти.
 *
 * @param rateToRub Стоимость одной единицы в рублях: десятичное число, не `Double`.
 * @param receivedAt Момент получения курса.
 */
data class CurrencyRate(
    val currency: Currency,
    val rateToRub: BigDecimal,
    val receivedAt: Instant
)
