package com.osvin.aichallenge.currency

/**
 * Источник курсов: то, что сервис умеет получать, но не умеет объяснять — откуда именно.
 *
 * Интерфейс здесь ради замены поставщика. У ЦБ, биржи и платного API разные адреса, форматы
 * ответа и лимиты запросов, и знать об этом должны только они сами: планировщик, история
 * и инструменты не должны меняться от того, чей ответ разобрали. Проверки подставляют сюда
 * поддельный источник и проверяют сбор без сети — то же основание, по которому в проекте
 * за интерфейсами спрятаны GitHub и модель.
 *
 * Ошибка получения — [CurrencyRateException], а не пустой список: пустой список значит
 * «поставщик ответил, но ни одного курса не назвал» (например, ответ без валют, которые
 * сервис отслеживает), и это другое состояние, чем «ответа не было». Смешав их, вызывающий
 * не отличил бы отсутствие данных от отказа сети и написал бы в лог не то, что случилось.
 */
interface CurrencyRateProvider {
    /**
     * Курсы на момент вызова: не больше одной записи на валюту, стоимость одной единицы
     * в рублях. Валют, которых в ответе не было, в списке тоже нет.
     *
     * @throws CurrencyRateException Поставщик не ответил, отказал или ответ не разобран.
     */
    suspend fun getRates(): List<CurrencyRate>
}

/** Курсы не получены: сеть, отказ поставщика или неразобранный ответ. */
class CurrencyRateException(message: String, cause: Throwable? = null) : Exception(message, cause)
