package com.osvin.aichallenge.currency

/**
 * Валюта, за курсом которой следит сервис: базовая валюта — рубль ([code] — код ISO 4217).
 *
 * Список закрытый и живёт кодом, а не настройкой. Под отслеживаемые валюты заведены объявление
 * инструмента, сводка и строки истории, поэтому «добавить валюту переменной окружения» значило
 * бы получить валюту, о которой инструмент не говорит: собранный по ней курс некуда положить,
 * а сводка о нём не знала бы. Новая валюта — правка перечисления, за которой видно всё, что
 * её касается.
 *
 * @param code Код валюты так, как его называют поставщик курсов и инструменты.
 */
enum class Currency(val code: String) {
    EUR("EUR"),
    USD("USD"),
    GEL("GEL");

    companion object {
        /**
         * Валюта по коду из ответа поставщика; null — такую валюту не отслеживаем.
         *
         * Регистр не важен: поставщики называют коды и заглавными, и строчными, а расхождение
         * в регистре не должно выглядеть как «валюты нет».
         */
        fun byCode(code: String): Currency? =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) }
    }
}
