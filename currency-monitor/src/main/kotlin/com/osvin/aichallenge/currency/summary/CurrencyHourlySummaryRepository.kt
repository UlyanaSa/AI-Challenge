package com.osvin.aichallenge.currency.summary

import com.osvin.aichallenge.currency.CurrencyStorageException
import java.time.Instant

/**
 * История часовых сводок: запись закрытого часа и выборка окна.
 *
 * Отдельный интерфейс рядом с историей курсов, а не её расширение: рядов два, и живут они
 * по разным правилам. Минутная история только дописывается и растёт каждую минуту, сводки
 * переписываются (час закрывается заново, пока по нему есть записи) и хранят уже посчитанное.
 * Свести это в один интерфейс значило бы обещать хранилищу операцию, которой у одного из двух
 * рядов нет.
 *
 * Закрытия в интерфейсе нет намеренно: база у обоих хранилищ одна и та же, и закрывает её тот,
 * кто её открыл, — хранилище курсов. Второй `close` на том же соединении был бы не отказом,
 * но и не смыслом: файл закрывается один раз, и знать об этом должны не все, кто в него пишет,
 * а один владелец.
 *
 * Отказы приходят [CurrencyStorageException] — по той же причине, что у истории курсов:
 * драйвер бросает свои исключения, а верхние слои о JDBC не знают.
 */
interface CurrencyHourlySummaryRepository {

    /**
     * Записывает сводки часов, заменяя уже записанные по тем же валюте и часу.
     *
     * Замена, а не отказ на повторной записи: час закрывается заново на каждом обходе, пока
     * по нему есть записи, и повтор обязан быть безобидным. Появившаяся позже запись того же
     * часа (например, после ручного `--once`) должна попасть в сводку, а не остаться в стороне.
     *
     * @return Сколько строк записано.
     * @throws CurrencyStorageException Сводки не записаны.
     */
    suspend fun save(summaries: List<CurrencyHourlySummary>): Int

    /**
     * Сводки всех валют за окно `[from, to]` по возрастанию часа.
     *
     * Границы — начала часов, обе входят в окно. Валюта в ответе есть у каждой строки: сводки
     * окна читаются одной выборкой, а не по валюте за раз, — иначе суточный отчёт делал бы
     * три запроса там, где хватает одного.
     *
     * @throws CurrencyStorageException Сводки не прочитаны.
     */
    suspend fun between(from: Instant, to: Instant): List<CurrencyHourlySummary>
}
