package com.osvin.aichallenge.currency

import java.time.Instant

/**
 * История курсов: запись и выборка. Хранилище отделено интерфейсом.
 *
 * Отделение здесь не «на будущее»: сводка и инструменты читают историю, планировщик в неё
 * пишет, и проверки подставляют хранилище в память — так считается сводка и проверяется путь
 * инструмента без файла базы. Интерфейс описывает только то, что этим потребителям нужно:
 * дописать обновление, взять последние значения, взять окно и взять предыдущее значение.
 * Ни «удалить», ни «обновить запись» здесь нет намеренно: история курсов только дописывается,
 * и ошибка поставщика не должна уносить прежние значения — это требование задания, а не
 * удобство, и оно выполняется отсутствием операции, а не аккуратностью вызывающего.
 *
 * Отказы хранилища приходят [CurrencyStorageException]: драйвер базы бросает свои исключения,
 * и превращать их в доменное — дело реализации, а не верхних слоёв, которые о JDBC не знают.
 */
interface CurrencyRateRepository {
    /**
     * Дописывает курсы в историю одной транзакцией.
     *
     * Транзакция, а не три вставки подряд: обновление — это один факт про один момент времени,
     * и половина обновления в истории выглядела бы как «в этот час знали только доллар».
     *
     * @return Сколько строк добавилось.
     * @throws CurrencyStorageException История не записана.
     */
    suspend fun save(rates: List<CurrencyRate>): Int

    /**
     * Последняя запись по каждой валюте, у которой история есть.
     *
     * Валюты без истории в списке отсутствуют, а не приходят нулём: «курс неизвестен» и «курс
     * равен нулю» — разные утверждения, и нулю здесь взяться неоткуда.
     *
     * @throws CurrencyStorageException История не прочитана.
     */
    suspend fun latest(): List<CurrencyRate>

    /**
     * Записи валюты за окно `[from, to]` по возрастанию времени получения.
     *
     * Окно задаётся с обеих сторон, потому что так его считает сводка: от «сейчас минус период»
     * до «сейчас». Записи из будущего в окно не попадут, даже если часы процесса убежали вперёд.
     *
     * @throws CurrencyStorageException История не прочитана.
     */
    suspend fun between(currency: Currency, from: Instant, to: Instant): List<CurrencyRate>

    /**
     * Последняя запись валюты, полученная строго до [before]: предыдущий известный курс.
     *
     * Строго до, а не «до или равно»: все валюты одного обновления записаны одним моментом,
     * поэтому нестрогое сравнение вернуло бы сам текущий курс — и «изменение» всегда было бы
     * нулевым. Если истории до этого момента нет, возвращается null: сравнивать текущий курс
     * не с чем, и это состояние видно вызывающему.
     *
     * @throws CurrencyStorageException История не прочитана.
     */
    suspend fun previous(currency: Currency, before: Instant): CurrencyRate?

    /** Закрывает хранилище: соединение и его ресурсы не должны пережить процесс. */
    fun close()
}

/** История не записана или не прочитана: отказ хранилища. */
class CurrencyStorageException(message: String, cause: Throwable? = null) : Exception(message, cause)
