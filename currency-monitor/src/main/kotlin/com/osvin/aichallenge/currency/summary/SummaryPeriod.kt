package com.osvin.aichallenge.currency.summary

import java.time.Duration

/**
 * Период сводки: окно, за которое считаются минимум, максимум и средний курс.
 *
 * Месяц — это ровно 30 дней, а не календарный месяц. Календарный зависит от того, когда его
 * спросили: 30 сентября он 30 дней, 31 октября — 31, а февраль короче любого из них, и одна
 * и та же сводка «за месяц» отвечала бы про разные окна — сравнить два месяца между собой было
 * бы нельзя. У суток и недели такой развилки нет: это 24 часа и 7 суток, и они одинаковы
 * в любой день.
 *
 * @param code Код периода на проводе (аргумент инструмента и поле ответа).
 * @param duration Длина окна.
 */
enum class SummaryPeriod(val code: String, val duration: Duration) {
    DAY("DAY", Duration.ofHours(24)),
    WEEK("WEEK", Duration.ofDays(7)),
    MONTH("MONTH", Duration.ofDays(30));

    companion object {
        /**
         * Период по коду из аргумента инструмента; null — такого периода нет.
         *
         * Регистр не важен: модель называет значения из схемы, но человек в ручном вызове
         * напишет `day`, и отказ за регистр выглядел бы придиркой. Проверка значения всё
         * равно нужна: схема ограничивает модель, а не того, кто прислал кадр руками.
         */
        fun byCode(code: String): SummaryPeriod? =
            entries.firstOrNull { it.code.equals(code, ignoreCase = true) }
    }
}
