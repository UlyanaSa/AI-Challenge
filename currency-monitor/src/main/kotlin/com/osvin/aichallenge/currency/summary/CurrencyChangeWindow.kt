package com.osvin.aichallenge.currency.summary

import java.time.Instant

/**
 * Изменение курсов за окно, собранное из сохранённых часовых сводок.
 *
 * Границы окна и его покрытие здесь отделены от самих чисел: спросили «за сутки», а сохранено
 * могло быть меньше суток — служба могла стоять, история могла только начаться. Тогда честный
 * ответ — «изменение за столько-то часов из запрошенных суток», а не молчаливое «такое же, как
 * за сутки». Поэтому в ответе три величины: сколько просили ([hours]), сколько часов закрыто
 * ([hoursCovered]) и какое окно они покрывают ([from], [to]).
 *
 * @param hours Запрошенное окно в часах.
 * @param from Начало первой сохранённой сводки окна; null — сохранённых сводок нет вовсе.
 * @param to Конец последней сохранённой сводки (начало её часа плюс час); null — сводок нет.
 * @param hoursCovered Сколько часовых сводок в окне (без пропусков судить нельзя, поэтому это
 *        именно число сохранённых часов, а не длина окна).
 * @param changes Изменение по каждой отслеживаемой валюте в объявленном порядке.
 */
data class CurrencyChangeWindow(
    val hours: Int,
    val from: Instant? = null,
    val to: Instant? = null,
    val hoursCovered: Int = 0,
    val changes: List<CurrencyChange> = emptyList()
)
