package com.osvin.aichallenge.indexing.search

import kotlin.math.sqrt

/**
 * Косинусная близость двух векторов одинаковой длины — мера того, насколько совпадают их
 * направления, а не длины.
 *
 * Считается по `Double`, хотя вход — `Float`: скалярное произведение и нормы суммируются по сотням
 * компонент, и float-накопление заметно теряло бы точность на хвосте.
 *
 * Нулевой вектор не имеет направления; вместо NaN возвращается 0.0 — «не похож ни на что». Ноль
 * здесь выбран сознательно: это значение совпадает с близостью ортогональных векторов, и поиск
 * не обязан отдельно разбирать пустой запрос.
 */
object CosineSimilarity {

    /**
     * Возвращает косинус между [a] и [b] в диапазоне от -1 до 1.
     *
     * Несовпадение длин — ошибка, а не «похожесть ноль»: векторы разной длины посчитаны в разных
     * пространствах, и их сравнение было бы числом без смысла.
     */
    fun cosine(a: List<Float>, b: List<Float>): Double {
        require(a.size == b.size) {
            "Нельзя сравнить векторы разной длины: ${a.size} и ${b.size}"
        }

        var dot = 0.0
        var normA = 0.0
        var normB = 0.0
        for (i in a.indices) {
            val x = a[i].toDouble()
            val y = b[i].toDouble()
            dot += x * y
            normA += x * x
            normB += y * y
        }

        if (normA == 0.0 || normB == 0.0) return 0.0
        return dot / (sqrt(normA) * sqrt(normB))
    }
}
