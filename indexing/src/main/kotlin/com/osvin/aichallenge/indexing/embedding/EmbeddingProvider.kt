package com.osvin.aichallenge.indexing.embedding

/**
 * Поставщик embeddings: текст на входе — вектор одинаковой длины на выходе.
 *
 * Провайдер не знает ни про стратегии chunking, ни про хранилище: ему на вход приходит готовая
 * строка. Поэтому одну и ту же реализацию используют оба индекса — и чанки, и поисковые запросы
 * считаются одной моделью, иначе similarity сравнивала бы векторы из разных пространств.
 *
 * [dimension] объявлена в контракте, а не спрятана в реализации: хранилище проверяет по ней, что
 * в индекс не попал вектор чужой длины, а поиск — что запрос посчитан той же моделью, что и чанки.
 */
interface EmbeddingProvider {

    /** Длина вектора. Все вызовы [embed] возвращают ровно столько чисел. */
    val dimension: Int

    /**
     * Считает embedding текста. Приостанавливаемая, потому что за контрактом может стоять
     * и локальная модель, и внешний API; наш провайдер локальный, но контракт от него не зависит.
     */
    suspend fun embed(text: String): List<Float>
}
