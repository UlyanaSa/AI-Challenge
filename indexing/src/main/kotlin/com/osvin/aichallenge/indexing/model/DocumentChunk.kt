package com.osvin.aichallenge.indexing.model

import kotlinx.serialization.Serializable

/**
 * Чанк документа: текст, который уходит в embedding, и метаданные, по которым видно его
 * происхождение.
 *
 * [id] однозначно определяет чанк: он строится из стратегии, документа, файла и порядкового
 * номера, поэтому два индекса, построенные из одного набора документов, не пересекаются по
 * ключам, а повторная индексация теми же стратегиями даёт те же самые ключи.
 */
@Serializable
data class DocumentChunk(
    val id: String,
    val content: String,
    val metadata: ChunkMetadata
)

/**
 * Метаданные чанка — минимум, который требует задание.
 *
 * [source] — имя файла, откуда взят текст. У структурной стратегии оно точное: чанк не выходит
 * за границу файла. У фиксированной — по началу чанка: чанк может пересекать границу файлов
 * (она для этой стратегии не существует), и тогда `source` называет файл, с которого чанк
 * начался. Это осознанная потеря: стратегия, которая не смотрит на структуру, не может честно
 * назвать один файл для текста, собранного из двух.
 *
 * [section] — ближайший заголовок раздела. У структурной стратегии он заполнен у всего, что
 * попало под заголовок; у фиксированной всегда `null`: заголовки она не разбирает.
 *
 * [title] — заголовок документа целиком, [chunkIndex] — порядковый номер чанка внутри своей
 * стратегии и документа.
 *
 * [pages] — страницы источника, на которые попал текст чанка (отсортированы, без повторов).
 * Пустой список означает «страницы неизвестны»: у файла без карты страниц их взять неоткуда.
 * Для фиксированной стратегии страницы считаются только по той части чанка, которая лежит
 * в файле из [source]: чанк, пересёкший границу файлов, уже назвал один файл из двух, и
 * приписывать ему страницы второго было бы второй такой же неточностью.
 */
@Serializable
data class ChunkMetadata(
    val source: String,
    val title: String?,
    val section: String?,
    val chunkIndex: Int,
    val strategy: ChunkingStrategyType,
    val pages: List<Int> = emptyList()
)

/**
 * Строит идентификатор чанка: `стратегия:документ/файл#номер`.
 *
 * Префикс стратегии обязателен: обе стратегии режут один и тот же текст, и без него чанк «Flow»
 * из фиксированного и из структурного индекса получил бы один ключ при том, что это разные
 * тексты. Номер внутри документа и файла уникален, потому что каждая стратегия обходит документ
 * ровно один раз.
 */
fun chunkId(
    strategy: ChunkingStrategyType,
    documentId: String,
    source: String,
    index: Int
): String = "${strategy.name.lowercase()}:$documentId/$source#$index"
