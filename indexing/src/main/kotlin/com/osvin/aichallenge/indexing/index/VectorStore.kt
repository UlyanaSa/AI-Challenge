package com.osvin.aichallenge.indexing.index

import com.osvin.aichallenge.indexing.search.SearchResult

/**
 * Хранилище индекса: сохранить чанк с вектором и найти ближайшие к вектору запроса.
 *
 * Одно хранилище держит одну стратегию: два индекса из задания — это два независимых экземпляра,
 * а не поле «стратегия» в одном. Иначе поиск по одной стратегии пришлось бы просить фильтром,
 * и «два независимых индекса» стали бы одним с условием в каждом запросе.
 *
 * Оба метода приостанавливаемые: за контрактом может стоять файл, база или сеть.
 */
interface VectorStore {

    /**
     * Сохраняет чанк с embedding. Повторная запись чанка с тем же `id` заменяет прежний:
     * индекс — это множество чанков, а не журнал прогонов.
     */
    suspend fun save(chunk: IndexedChunk)

    /**
     * Возвращает чанк с вектором по `id`; `null` — такого чанка в индексе нет.
     *
     * Нужно там, где показывают сам вектор: поиск отдаёт близость одним числом, а объяснить его
     * можно только векторами, и лежат они в индексе. Отсутствие чанка — не ошибка: спрашивающий
     * мог прийти с идентификатором из другого прогона, и это честный ответ «такого чанка нет».
     */
    suspend fun get(id: String): IndexedChunk?

    /**
     * Возвращает до [limit] ближайших чанков, отсортированных по убыванию близости.
     *
     * Длина [embedding] должна совпадать с длиной векторов индекса — иначе запрос посчитан
     * другой моделью, и близость была бы числом без смысла; несовпадение — ошибка, а не пустой
     * результат.
     */
    suspend fun search(embedding: List<Float>, limit: Int): List<SearchResult>
}
