package com.osvin.aichallenge.indexing.model

/**
 * Стратегия, которой документ режется на чанки.
 *
 * Тип хранится в метаданных каждого чанка, а не выводится из того, какой индексатор его создал:
 * по индексу видны чанки обеих стратегий одновременно, и «чей это чанк» — свойство самого чанка,
 * а не место, где он лежит.
 */
enum class ChunkingStrategyType {
    FIXED_SIZE,
    STRUCTURAL
}
