package com.osvin.aichallenge.indexing.model

import kotlinx.serialization.Serializable

/**
 * Документ набора: один логический текст, состоящий из одного или нескольких файлов.
 *
 * Уровни `Document → File → Heading → Section → Content` из задания разделены так: документ —
 * это тема, файл — её часть на диске, заголовок открывает раздел внутри файла. Файлов у документа
 * может быть несколько сразу (например, «Kotlin Coroutines» — четыре страницы), поэтому граница
 * файла — это тоже структурная граница, а не только граница между документами: стратегия,
 * которая её не видит, склеивает конец одного файла с началом другого.
 *
 * [id] — устойчивый ключ документа: он попадает в идентификаторы чанков и переживает повторную
 * индексацию. [title] — человеческое имя набора; в метаданные чанка идёт именно оно.
 */
@Serializable
data class Document(
    val id: String,
    val title: String?,
    val files: List<DocumentFile>
)

/**
 * Файл документа: имя (оно же `source` в метаданных чанка), его содержимое в Markdown и карта
 * страниц.
 *
 * Имена файлов внутри набора документов уникальны: `source` должен называть ровно один файл,
 * иначе по метаданным нельзя было бы понять, откуда взят чанк.
 *
 * [pages] — страницы источника ([PageMark]), отсортированные по смещению. Пустой список —
 * страницы неизвестны: так выглядит файл, у которого нет вёрстки с нумерацией (синтетический
 * текст, файл, собранный вручную), и это честное «не знаю», а не «страница 0». Чанк спрашивает
 * страницы у файла по своим смещениям ([pagesIn]), поэтому карта страниц — свойство текста файла,
 * а не отдельного чанка: одна и та же страница обслуживает все чанки, которые на неё попали.
 */
@Serializable
data class DocumentFile(
    val name: String,
    val content: String,
    val pages: List<PageMark> = emptyList()
) {

    /** Страница, на которой лежит текст со смещением [offset]; `null`, если страницы неизвестны. */
    fun pageAt(offset: Int): Int? = pages.lastOrNull { it.offset <= offset }?.page

    /**
     * Страницы, на которых начинается текст в диапазоне `[from, to]`: страница начала диапазона
     * плюс все страницы, чей первый блок попал внутрь. Пустой список — страницы неизвестны.
     *
     * Страница начала берётся отдельно, потому что диапазон часто начинается в середине страницы:
     * первый маркер внутри него тогда говорит уже о следующей странице, и без этой добавки чанк
     * потерял бы страницу, с которой он начинается.
     */
    fun pagesIn(from: Int, to: Int): List<Int> {
        if (pages.isEmpty() || to < from) return emptyList()
        val result = ArrayList<Int>(2)
        pageAt(from)?.let { result += it }
        pages.filter { it.offset in (from + 1)..to }.forEach { result += it.page }
        return result.distinct().sorted()
    }
}
