package com.osvin.aichallenge.indexing.model

/**
 * Текст страниц PDF — в текст корпуса: перенесённые строки склеиваются в абзацы, страницы
 * размечаются маркерами.
 *
 * Обратная сторона [PageMarkers]: тот снимает маркеры и считает смещения, этот ставит маркеры по
 * страницам, которые пришли от разбора PDF. Маркер печатается на границе абзацев — так он не
 * разрезает абзац, и текст после [PageMarkers.stripAndIndex] совпадает с исходным.
 *
 * **Почему строки надо склеивать.** PDF не хранит абзацев: он хранит строки вёрстки, разбитые по
 * ширине колонки. Если оставить их как есть, каждый абзац станет десятком блоков, структурная
 * нарезка будет резать по границам строк, а фрагмент ответа на странице — показывать одну строку.
 * Границу абзаца приходится восстанавливать по вёрстке, и признак здесь один: строка продолжается
 * следующей, если она не кончается знаком конца предложения и не короче половины медианной длины
 * строки страницы. Медиана, а не абсолютный порог: у документов разная ширина колонки, и одно
 * число подошло бы только тому, на котором его подобрали. Короткая строка — это заголовок, пункт
 * списка или последняя строка абзаца; продолжаться такой текст не может.
 *
 * **Заголовки приходят уже размеченными.** Кто читает PDF, тот видит и кегль строки, и отмечает
 * заголовок знаком `#` ([PdfSource] в модуле страницы): строка-заголовок — отдельный блок, и
 * склеивать её с соседним абзацем нельзя, иначе раздел перестал бы называться так, как он назван
 * в книге, и структурная нарезка потеряла бы свою границу. Поэтому строки с `#` здесь не
 * продолжаются и не продолжают: они остаются блоками ровно того размера, каким их поставила вёрстка.
 *
 * **Чего этот разбор по-прежнему не делает.** Списки и таблицы остаются текстом: у PDF нет ни
 * разметки, ни стилей в текстовом потоке, а пункт списка отличается от абзаца только вёрсткой,
 * которую здесь не восстанавливают. Это честная граница: обещать разметку там, где её нет,
 * значило бы выдумывать структуру.
 */
object PageText {

    /** Знаки, которыми заканчивается предложение или пункт; после них строка завершает абзац. */
    private const val SENTENCE_END = ".!?:;…»"

    /** Перенос слова в вёрстке: «архитек-» + «туры» — это одно слово. */
    private const val HYPHEN = '-'

    /** Знак заголовка, поставленный тем, кто читает вёрстку: `#`, `##`, … */
    private const val HEADING = '#' 

    /**
     * Собирает текст корпуса из текстов страниц: страница с номером [firstPage] + индекс идёт
     * с маркером `<!-- page:N -->`. Пустые страницы маркера не получают — страница без текста
     * (обложка, вкладка, разворот с одной картинкой) не вводит в заблуждение «стр. 7» у чанка,
     * который на ней не лежит.
     */
    fun reflow(pages: List<String>, firstPage: Int = 1): String {
        val blocks = ArrayList<String>()
        pages.forEachIndexed { index, page ->
            val paragraphs = paragraphs(page)
            if (paragraphs.isEmpty()) return@forEachIndexed
            blocks += "<!-- page:${firstPage + index} -->"
            blocks += paragraphs
        }
        // Абзацы разделяются пустой строкой: текст корпуса — markdown, и блоком считается абзац.
        return if (blocks.isEmpty()) "" else blocks.joinToString("\n\n") + "\n"
    }

    /** Абзацы одной страницы: склеенные строки вёрстки. */
    internal fun paragraphs(page: String): List<String> {
        val lines = page.split("\n").map { it.trim() }.filter { it.isNotEmpty() }
        if (lines.isEmpty()) return emptyList()

        val median = lines.map { it.length }.sorted()[lines.size / 2]
        val paragraphs = ArrayList<String>()
        var current = lines.first()

        for (line in lines.drop(1)) {
            val joined = continueWith(current, line, median)
            if (joined == null) {
                paragraphs += current
                current = line
            } else {
                current = joined
            }
        }
        paragraphs += current
        return paragraphs
    }

    /**
     * Продолжение абзаца или `null`, если [next] начинает новый.
     *
     * Порядок проверок существенен: заголовок проверяется первым — он короткий, и по медиане он
     * сошёл бы за продолжение, а перенос слова проверяется до остальных признаков, потому что такая
     * строка заканчивается дефисом и выглядела бы концом абзаца.
     */
    private fun continueWith(current: String, next: String, median: Int): String? {
        if (current.startsWith(HEADING) || next.startsWith(HEADING)) return null
        if (current.length < median / 2) return null
        if (current.endsWith(HYPHEN) && next.first().isLowerCase()) {
            return current.dropLast(1) + next
        }
        if (current.last() in SENTENCE_END) return null
        // Строка, начинающаяся не с буквы, — это пункт списка, номер страницы или подпись рисунка.
        if (!next.first().isLetter()) return null
        return "$current $next"
    }
}
