package com.osvin.aichallenge.indexing.pipeline

/**
 * Поисковый запрос эксперимента: сам вопрос и раздел-эталон, в котором лежит ответ.
 *
 * Эталон задан парой «файл + раздел», а не готовым текстом: текст раздела берётся из корпуса
 * (см. [Sections]), так что эталон не может разойтись с документами. Каждый раздел выбран так,
 * чтобы отвечать именно на свой вопрос и не дублировать соседние — иначе оценка Top-3 говорила
 * бы о совпадении слов в корпусе, а не о работе стратегии.
 */
data class QuerySpec(
    val text: String,
    val source: String,
    val section: String
)

/**
 * Десять запросов эксперимента — вдвое больше минимума задания (пять): по одному запросу
 * выборка шумная, и разница стратегий тонет в случайности ранжирования. Вопросы покрывают все три
 * главы части, главные принципы организации компонентов (REP, CCP, CRP, ADP, SDP, SAP) и разные
 * по характеру разделы — от коротких определений до разделов с подразделами.
 *
 * Вопросы сформулированы так, как их задал бы читатель, а не нарезкой слов из текста: названия
 * принципов в них есть, но эти же слова много раз встречаются и в теле разделов, а не только
 * в заголовках, — поэтому лексический поиск может найти ответ по любой из стратегий, и разница
 * в результатах — след нарезки, а не подсказки в формулировке.
 *
 * Разделы выбраны «листовыми» либо такими, у которых свой текст до первого подраздела сравним
 * по размеру с чанком: эталон обязан быть того же масштаба, что и находимый фрагмент, иначе
 * в него попал бы материал соседних разделов.
 *
 * Один запрос — эталонный: он сформулирован пользователем дословно, и его формулировка
 * расходится с переводом книги. Пользователь называет принцип «принципом общей замкнутости»,
 * а в корпусе он переведён как «принцип согласованного изменения», поэтому у запроса и у раздела
 * общего только сокращение (CCP) и слова «классы», «компонент». Это честная проверка поиска:
 * ответ лежит в разделе, названном другими словами, и находится он по тексту, а не по совпадению
 * заголовка с вопросом.
 */
