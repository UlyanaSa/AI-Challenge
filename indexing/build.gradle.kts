plugins {
    alias(libs.plugins.kotlinJvm)
    // Индекс хранится в JSON: чанк вместе с embedding пишется на диск и читается обратно,
    // поэтому форма хранения описана в коде, а не собирается руками из строк.
    alias(libs.plugins.kotlinxSerialization)
}

group = "com.osvin.aichallenge"
version = "1.0.0"

/**
 * Локальная индексация документов: chunking двумя стратегиями, embeddings, индекс и поиск.
 *
 * Модуль отдельный, а не часть `:server`, по предмету: это не HTTP-маршрут и не MCP-инструмент,
 * а вычислительный конвейер, у которого нет ни клиента, ни сети. Embeddings считаются локально,
 * индекс лежит файлом рядом с процессом, а результат работы — отчёт сравнения двух стратегий
 * в консоли. Серверу приложения такой конвейер не нужен: он его не вызывает и о нём не знает.
 * Страница дня 21 — отдельный модуль `:indexing-ui`, который берёт конвейер зависимостью: HTTP
 * и статика в самом конвейере были бы лишними.
 *
 * Зависимостей ровно две: сериализация для файла индекса и корутины для suspend-контрактов
 * (`EmbeddingProvider.embed`, `VectorStore.save/search`) — те же контракты, что в задании.
 * HTTP-клиента и ключей API здесь нет: embedding-провайдер локальный и детерминированный,
 * поэтому прогон воспроизводим, а сравнение стратегий не зависит от сети и стоимости.
 */
dependencies {
    implementation(libs.kotlinx.serialization.json)
    implementation(libs.kotlinx.coroutines.core)

    testImplementation(libs.kotlin.test)
    testImplementation(libs.kotlinx.coroutines.core)
}

/**
 * Прогон эксперимента: `./gradlew :indexing:indexReport`.
 *
 * Собирает набор документов из тестовых ресурсов, индексирует его обеими стратегиями, печатает
 * статистику, выполняет поисковые запросы по двум индексам, сравнивает стратегии по критериям
 * задания и показывает примеры, где Fixed Size разрезал логически связанный фрагмент.
 *
 * Набор книги лежит в `src/test/resources`: своего корпуса у приложения нет — текст приходит
 * из PDF, который загружает человек на странице дня. Конвейеру для сравнения стратегий нужен
 * неизменный набор, поэтому у него есть фикстура, и прогон идёт по тестовому classpath.
 *
 * Печать идёт в стандартный вывод: отчёт — это работа задачи, а не побочный эффект теста,
 * поэтому запуск отдельной задачей, а не `Test`.
 */
val indexReport by tasks.registering(JavaExec::class) {
    group = "verification"
    description = "Индексация набора документов двумя стратегиями и сравнение результатов поиска"
    mainClass.set("com.osvin.aichallenge.indexing.ApplicationKt")
    classpath = sourceSets["test"].runtimeClasspath
    // Отчёт пишется заново при каждом запуске: он зависит от корпуса и от стратегий, а не от
    // входов задачи, и его цель — показать числа текущего прогона.
    outputs.upToDateWhen { false }
}
