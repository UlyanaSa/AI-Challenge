/**
 * Бенчмарк дня 29: сравнение сборок одной и той же локальной модели на кейсе «вопросы по
 * Kotlin/Kotlin Multiplatform».
 *
 * Модуль отдельный, потому что это измерительный прибор, а не часть чата: он не отвечает
 * человеку, а считает числа одного прогона — среднюю оценку по набору вопросов, расход
 * токенов, время и потребление памяти демоном. Страница чата к нему не обращается, и он
 * к ней: измерение остаётся в консольной задаче, где его видно и можно повторить.
 *
 * Зависимостей ровно две, и обе — уже существующие половины проекта:
 * - `:agent` — контракт `LlmClient`, DTO запроса/ответа и конфигурация провайдера с окном
 *   контекста: бенчмарк не заводит второй транспорт, он спрашивает модель тем же клиентом,
 *   которым спрашивает её чат, и потому измеряет именно то, чем люди пользуются;
 * - `:rag` — проверка ответа (`Check`) и тип контрольного вопроса (`ControlQuestion`):
 *   оценка обязана быть той же самой функцией, что у дня 22, и вторая формула здесь была бы
 *   вторым мнением о качестве, которое ни с чем не сравнить. Фактов, страниц и RAG в этом
 *   модуле нет вовсе: у вопросов кейса пустой список страниц, и ответ берётся из знаний
 *   модели, а не из корпуса.
 *
 * Ktor-клиент нужен как зависимость модуля по той же причине, что у `:rag`: `:agent` отдаёт
 * наружу только контракт, а HTTP-запросу (и запросу чата, и снимку ресурсов демона) нужен
 * движок и JSON-режим клиента.
 */
dependencies {
    implementation(project(":agent"))
    implementation(project(":rag"))

    implementation(libs.kotlinx.serialization.json)
    implementation(libs.kotlinx.coroutines.core)
    implementation(libs.bundles.ktor.client)
    implementation(libs.ktor.serialization.kotlinx.json)

    testImplementation(libs.kotlin.test)
    testImplementation(libs.kotlinx.coroutines.core)
}

/**
 * Прогон дня: `./gradlew :llm-tuning:tuningDemo`.
 *
 * Прогон отвечает на десять вопросов кейса каждым профилем сборки — «как сейчас», «+ окно
 * контекста», «+ инструкция под кейс» и «окно + инструкция + бюджет», — сверяет ответы с
 * ожиданиями набора той же проверкой, что у дня 22, печатает сравнение и кладёт отчёт
 * в каталог прогона.
 *
 * Живого флага здесь нет, и это отличие от `ragDemo` намеренное: прогон обращается не
 * к платному API, а к демону на этой машине, ключа ему не нужно, а случайный запуск без
 * демона заканчивается подсказкой о `ollama serve`, а не отказом транспорта. Печать идёт
 * в стандартный вывод: сравнение — работа задачи, а не побочный эффект теста, поэтому
 * запуск отдельной задачей, как у `:indexing:indexReport`.
 */
val tuningDemo by tasks.registering(JavaExec::class) {
    group = "verification"
    description = "Сравнение сборок локальной модели на вопросах о Kotlin/Kotlin Multiplatform"
    mainClass.set("com.osvin.aichallenge.tuning.TuningCliKt")
    classpath = sourceSets["main"].runtimeClasspath
    // Каталогом запуска берётся корень проекта, а не модуль: каталог прогона по умолчанию
    // (`build/llm-tuning`) считается от корня, и при запуске из каталога модуля он указывал бы
    // в `llm-tuning/build/llm-tuning`, то есть в другое место, чем у отчётов остальных дней.
    workingDir = rootProject.projectDir
    // Отчёт пишется заново при каждом запуске: он зависит от модели, демона и профилей, а не от
    // входов задачи, и его цель — показать числа текущего прогона.
    outputs.upToDateWhen { false }
}
