 * Десять вопросов кейса — про ядро Kotlin и механику Kotlin Multiplatform.
 *
 * Набор — это измерительный прибор сравнения, и подбирался он не по интересности, а по трём
 * свойствам, без которых числа сравнения ничего не значат. **Проверяемость**: у каждого вопроса
