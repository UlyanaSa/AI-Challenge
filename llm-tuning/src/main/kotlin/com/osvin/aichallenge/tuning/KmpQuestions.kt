 * самого ответа.
 *
 * Вопросы нигде не повторяют текст ожидания: у вопроса, в который вписан ответ, модель показала бы
 * умение повторить вопрос, а не знание. Формулировки — как у человека, который пишет на Kotlin и
 * спрашивает о том, что в языке есть, но подробностей не помнит.
 *
