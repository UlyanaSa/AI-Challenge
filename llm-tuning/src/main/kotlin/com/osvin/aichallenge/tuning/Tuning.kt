package com.osvin.aichallenge.tuning

import com.osvin.aichallenge.agent.LlmProvider
import com.osvin.aichallenge.agent.LlmProviderConfig
import com.osvin.aichallenge.agent.LocalLlmClient
import com.osvin.aichallenge.models.config.AppConfig

/**
 * Профиль сборки модели: одно условие ответа целиком.
 *
 * Профиль, а не «набор флагов в прогоне», потому что условие обязано быть напечатано: числа
 * сравнения («стало лучше») без названного условия не объяснить, а по одной строке консоли
 * нельзя понять, чем «после» отличается от «до». Здесь лежит всё, чем ответ может отличаться,
 * и ни одно из этих полей не задаётся в другом месте: второй экземпляр условия разошёлся бы
 * с первым молча, и отчёт описывал бы не тот прогон, который был.
 *
 * @param id Короткое имя профиля для отчёта и аргумента `--config`: `baseline`, `context`,
 *        `template` или `optimized`.
 * @param title Чем профиль отличается в двух словах — для заголовка в отчёте.
 * @param note То же словами: что именно изменено против предыдущего профиля. Печатается рядом
 *        с числами, потому что «+ окно контекста» без числа окна — не условие, а обещание.
 * @param config Настройки транспорта: провайдер, имя модели, окно контекста, температура и
 *        рассуждение. Окно лежит здесь, а не в запросе, потому что окно — свойство загруженной
 *        модели у демона: два запроса с разными окнами заставили бы его перезагружать модель
 *        между вопросами, и разница во времени получилась бы у транспорта, а не у условий ответа.
 * @param systemPrompt Инструкция под кейс; `null` — как в чате дня 27, где своего system prompt
 *        у запроса нет и его роль играет первое сообщение диалога (на первом ходу — сам вопрос).
 *        Различие видно в отчёте строкой «системная инструкция: есть/нет», и это единственная
 *        ось сравнения, которая меняет не длину запроса, а поведение модели.
 * @param maxTokens Бюджет ответа (`num_predict` у Ollama); `null` — бюджет не задан и демон
 *        решает сам, сколько писать. Поле необязательное, но все четыре профиля его задают:
 *        чат дня 27 отправляет бюджет явно ([AppConfig.DEFAULT_MAX_TOKENS]), а профиль с
 *        неограниченным ответом отличался бы от него не одной осью, а двумя сразу — и
 *        «улучшением» оказался бы не тот шаг, который измерялся.
 */
data class Tuning(
    val id: String,
    val title: String,
    val note: String,
    val config: LlmProviderConfig,
    val systemPrompt: String?,
    val maxTokens: Int?
)

/**
 * Профили сравнения и инструкция под кейс — в одном месте.
 *
 * Сравнение дня 29 отвечает на вопрос «что изменилось в ответе, если тронуть одно условие», и
 * профили выстроены лестницей: каждый следующий отличается от предыдущего ровно одним шагом.
 * Иначе разница между колонками отчёта была бы суммой изменений, и по ней нельзя было бы сказать,
 * что именно дало прибавку: окно, инструкция или бюджет.
 *
 * Шаги лестницы выбраны по измеренной причине, а не «на всякий случай»:
 * - **окно контекста** — демон по умолчанию обрезает запрос по 4096 токенам и делает это молча:
 *   ответ приходит ответом, хотя вопрос дошёл до модели не весь. Профиль `context` поднимает окно
 *   до 8192 и показывает, даёт ли это что-то там, где запрос действительно длинный;
 * - **инструкция под кейс** ([KMP_RULES]) — маленькая модель на вопрос о KMP отвечает и «вообще»:
 *   переводит имена API, рассуждает вслух и тратит на это бюджет. Инструкция задаёт форму ответа
 *   без единого факта из ответа: она ничего не подсказывает, а только требует держаться кейса;
 * - **бюджет ответа** — у thinking-модели рассуждение идёт из того же бюджета, что текст ответа.
 *   Профиль `optimized` ограничивает его 512 токенами: если рассуждение съедало ответ целиком,
 *   это видно числом, а не догадкой.
 *
 * Умолчания базового профиля названы явно ([LocalLlmClient]), а не взяты «как получится»:
 * сравнение — это измерение до и после, и если умолчание транспорта когда-нибудь изменится,
 * изменится и профиль `baseline`, а вместе с ним и вывод отчёта. Явные значения держат «до»
 * тем же самым вне зависимости от правок в `:agent`.
 */
object Tunings {

    /**
     * Окно контекста профилей «с окном»: `8192` — вдвое больше умолчания демона.
     *
     * Выбрано вдвое, а не максимумом модели (40960): окно занимает память под кэш внимания, и
     * платить её на каждом вопросе незачем. Вдвое же — потому что вопрос кейса с инструкцией и
     * историей перерастает 4096, а до 8192 помещается целиком; если бы и этого не хватало,
     * разница между профилями была бы обрезкой, а не ответом.
     */
    private const val WINDOW_CONTEXT = 8192

    /**
     * Бюджет ответа оптимизированного профиля: `512` токенов.
     *
     * Меньше бюджета чата (8192) в шестнадцать раз, и это ось сравнения, а не экономия: ответ
     * кейса — три-пять предложений (их и требует инструкция), то есть около сотни токенов, а
     * остальной бюджет у thinking-модели уходит на рассуждение. Ограничение показывает, платит
     * ли модель за ответ рассуждением и остаётся ли в ответе текст, когда бюджет кончился.
     */
    private const val BUDGET_OPTIMIZED = 512

    /**
     * Температура профиля `temperature`: `0.7` — рекомендация самой модели.
     *
     * Не круглое число «на глаз»: столько называет `/api/show` для `qwen3:1.7b` (вместе с
     * `top_p 0.95` и `top_k 20`), и если температуру трогать, то именно до рекомендованной,
     * а не до произвольной. Дни 26–27 выбрали `0` не из осторожности, а по замеру: при `0.7`
     * маленькая модель плывёт в написании имён API, а сравнение профилей перестаёт быть
     * сравнением — повтор того же вопроса даёт другой ответ. Профиль дня 29 проверяет это
     * число ещё раз, уже на кейсе с инструкцией.
     */
    private const val TEMPERATURE_MODEL = 0.7

    /**
     * Температура обеих сборок в окнах чата: `0.7` — рекомендация самой модели.
     *
     * В прогоне ([ALL]) температура ступеней остаётся `0`, и это не осторожность: при `0.7` два
     * прогона одного профиля дают разные баллы, то есть разницу между соседними колонками нельзя
     * приписать профилю (замер в §4 отчёта дня 29). В чате сравнивают не ступени, а два ответа на
     * один вопрос, и повторяемость здесь не нужна — нужна живость ответа: у обеих сборок стоит
     * одно и то же число, поэтому разницу между окнами нельзя отнести к температуре, а не к сборке.
     */
    private const val TEMPERATURE_CHAT = 0.7

    /**
     * Настройки, повторяющие сегодняшнее поведение чата в локальном режиме.
     *
     * Значения не «умолчания типа», а измеренные умолчания транспорта дня 26-27: провайдер —
     * локальный демон, модель `qwen3:1.7b`, температура `0` (при `0.7` маленькая модель
     * нестабильна в написании и счёте), рассуждение включено, окно — умолчание демона.
     */
    private val BASE: LlmProviderConfig = LlmProviderConfig(
        provider = LlmProvider.LOCAL,
        ollamaModel = LocalLlmClient.DEFAULT_MODEL,
        ollamaTimeoutMillis = LocalLlmClient.DEFAULT_TIMEOUT_MILLIS,
        ollamaThink = LocalLlmClient.DEFAULT_THINK,
        ollamaTemperature = LocalLlmClient.DEFAULT_TEMPERATURE,
        ollamaNumCtx = LocalLlmClient.DEFAULT_NUM_CTX
    )

    /**
     * Инструкция под кейс: форма ответа, а не подсказка.
     *
     * Ни одного факта о Kotlin здесь нет и быть не может: инструкция, в которой лежит ответ,
     * измеряла бы чтение промпта, а не знание модели. Каждое правило отвечает за свою ось
     * сравнения:
     *
     * - **по-русски** — вопросы кейса русские, и ответ на другом языке нельзя ни прочитать, ни
     *   сверить с ожиданием; у qwen3 это ещё и заметно по рассуждению: без требования языка
     *   модель часто рассуждает по-английски, и написание имён API в ответе плывёт;
     * - **опираться на стандартную библиотеку и механику KMP** — в вопросах нет номеров версий
     *   и редких библиотек, и требование держит модель в устойчивом ядре языка вместо выдуманных
     *   «улучшений последней версии»;
     * - **имена API латиницей и как есть** — проверка фактов ищет латинские признаки (`expect`,
     *   `actual`, `StateFlow`): перевод имени («ожидаемое объявление») сделал бы ответ
     *   непроверяемым, а читателю — бесполезным, потому что в коде эти имена всё равно латинские;
     * - **три-пять предложений без рассуждений вслух** — бюджет профиля `optimized` ограничен, и
     *   ответ, начавшийся с размышлений, до текста может не дойти; короткий ответ к тому же
     *   сравним между профилями по длине, а не по запасу времени;
     * - **признавать незнание** — снижает правдоподобное сочинение: у вопроса, которого модель
     *   не знает, честное «не знаю» стоит 0 баллов, но не тянет за собой выдуманные факты,
     *   которые читались бы как знание.
     */
    val KMP_RULES: String = """
        Ты отвечаешь на вопросы о языке Kotlin и Kotlin Multiplatform.
        Отвечай по-русски.
        Опирайся на факты стандартной библиотеки Kotlin и механики Kotlin Multiplatform, не выдумывай новое.
        Имена API (классы, функции, аннотации, имена таргетов) называй латиницей и как есть, без перевода.
        Отвечай тремя-пятью предложениями по делу и не рассуждай вслух.
        Если ответа не знаешь — скажи об этом прямо.
    """.trimIndent()

    /**
     * Профили в порядке лестницы: от «как сейчас» к «окно + инструкция + бюджет».
     *
     * Порядок фиксирован, потому что так же идут прогоны и так же читается отчёт: каждый
     * следующий профиль отличается от предыдущего одним шагом, и разницу между соседними
     * колонками можно объяснить словами, а не подбором.
     */
    val ALL: List<Tuning> = listOf(
        Tuning(
            id = "baseline",
            title = "как сейчас",
            note = "чат дня 27 как есть: локальный транспорт без инструкции, окно " +
                "${LocalLlmClient.DEFAULT_NUM_CTX} (умолчание демона), бюджет ${AppConfig.DEFAULT_MAX_TOKENS}",
            config = BASE,
            systemPrompt = null,
            maxTokens = AppConfig.DEFAULT_MAX_TOKENS
        ),
        Tuning(
            id = "context",
            title = "+ окно контекста",
            note = "то же, но окно поднято до $WINDOW_CONTEXT токенов: длинный запрос перестаёт " +
                "обрезаться демоном молча",
            config = BASE.copy(ollamaNumCtx = WINDOW_CONTEXT),
            systemPrompt = null,
            maxTokens = AppConfig.DEFAULT_MAX_TOKENS
        ),
        Tuning(
            id = "template",
            title = "+ инструкция под кейс",
            note = "то же плюс системная инструкция: форма ответа задана, окно $WINDOW_CONTEXT",
            config = BASE.copy(ollamaNumCtx = WINDOW_CONTEXT),
            systemPrompt = KMP_RULES,
            maxTokens = AppConfig.DEFAULT_MAX_TOKENS
        ),
        optimizedFrom(BASE),
        Tuning(
            id = "temperature",
            title = "окно + инструкция + бюджет, температура 0.7",
            note = "то же, но температура 0.7 (рекомендованная самой моделью в /api/show) вместо 0: " +
                "проверка, что нулевая температура здесь не теряет живости ответа, а платит за неё " +
                "повторяемостью прогона",
            config = BASE.copy(ollamaNumCtx = WINDOW_CONTEXT, ollamaTemperature = TEMPERATURE_MODEL),
            systemPrompt = KMP_RULES,
            maxTokens = BUDGET_OPTIMIZED
        ),
        Tuning(
            id = "nothink",
            title = "окно + инструкция + бюджет, без рассуждения",
            note = "то же, но рассуждение выключено: у thinking-модели рассуждение идёт из того " +
                "же бюджета ($BUDGET_OPTIMIZED токенов на рассуждение и ответ вместе), и оно же " +
                "занимает время до первого слова ответа",
            config = BASE.copy(ollamaNumCtx = WINDOW_CONTEXT, ollamaThink = false),
            systemPrompt = KMP_RULES,
            maxTokens = BUDGET_OPTIMIZED
        )
    )

    /**
     * Профиль оптимизированной сборки поверх настроек, которые уже действуют.
     *
     * Окно, инструкция и бюджет берутся у профиля, а настройки запуска — снаружи, и это не
     * удобство, а условие честного сравнения. Отвечает сборка той же моделью, что запущена
     * у сервера: его настройки читаются из окружения (`OLLAMA_MODEL`), и если прогон квантования
     * идёт по `qwen3:1.7b-q8_0`, отчёт обязан говорить именно о ней — иначе числа одного прогона
     * нельзя было бы приложить к другому. Адрес демона, срок запроса и рассуждение при этом тоже
     * остаются теми, что действуют у сервера: это настройки запуска, а не оси оптимизации.
     *
     * В наборе профилей ([ALL]) та же функция вызывается от [BASE] — так «optimized» в отчёте
     * и «optimized» в прогоне не могут разойтись ни заголовком, ни примечанием, ни значениями
     * окна и бюджета: их задаёт один и тот же код. Окна чата собираются отдельно
     * ([chatOptimizedFrom]): у них своя температура, и подменять её здесь значило бы изменить
     * ступень прогона.
     *
     * @param base Настройки, которые уже действуют: провайдер, модель, температура, рассуждение.
     */
    fun optimizedFrom(base: LlmProviderConfig): Tuning = Tuning(
        id = "optimized",
        title = "окно + инструкция + бюджет",
        note = "всё вместе: окно $WINDOW_CONTEXT, инструкция под кейс и бюджет ответа " +
            "$BUDGET_OPTIMIZED токенов вместо ${AppConfig.DEFAULT_MAX_TOKENS} — видно, остаётся ли " +
            "текст ответа, когда рассуждению нечем платить",
        config = base.copy(ollamaNumCtx = WINDOW_CONTEXT),
        systemPrompt = KMP_RULES,
        maxTokens = BUDGET_OPTIMIZED
    )

    /**
     * Сборка «как сейчас» для левого окна чата поверх настроек, которые уже действуют.
     *
     * От ступени `baseline` прогона ([ALL]) отличается двумя настройками, и обе заданы здесь,
     * а не в маршруте сервера: температура взята из [TEMPERATURE_CHAT] — та же, что у соседнего
     * окна, иначе разницу между окнами можно было бы отнести к температуре, — а рассуждение
     * выключено: «как сейчас» отвечает без него. Рассуждение у thinking-модели идёт из того же
     * бюджета, что текст ответа, и занимает время до первого слова: в прогоне та же настройка
     * (ступень `nothink`) оказалась в шесть раз быстрее остальных и на один факт из 29 беднее —
     * здесь она стоит у сборки, которую оптимизируют, а не у результата оптимизации.
     *
     * Окно и бюджет — настройки запуска: окно приходит от сервера (`OLLAMA_NUM_CTX`, умолчание
     * демона), бюджет — бюджет чата ([AppConfig.DEFAULT_MAX_TOKENS]), как у ступени `baseline`.
     *
     * @param base Настройки, которые уже действуют: провайдер, модель, адрес демона, окно.
     */
    fun chatBaselineFrom(base: LlmProviderConfig): Tuning = Tuning(
        id = "baseline",
        title = "как сейчас",
        note = "сборка «как сейчас» в окне чата: без инструкции, окно ${base.ollamaNumCtx} " +
            "(настройка запуска сервера), бюджет ${AppConfig.DEFAULT_MAX_TOKENS}, " +
            "температура $TEMPERATURE_CHAT, без рассуждения",
        config = base.copy(ollamaTemperature = TEMPERATURE_CHAT, ollamaThink = false),
        systemPrompt = null,
        maxTokens = AppConfig.DEFAULT_MAX_TOKENS
    )

    /**
     * Оптимизированная сборка для правого окна чата поверх настроек, которые уже действуют.
     *
     * Та же сборка, что ступень `optimized` прогона ([optimizedFrom]), с одним отличием: её
     * температура — [TEMPERATURE_CHAT], а не `0` ступени. Профиль берётся у [optimizedFrom],
     * а не переписывается здесь: окно, бюджет, инструкция и примечание у прогона и у окна чата
     * обязаны быть одни и те же, и второй их список разошёлся бы с первым молча.
     *
     * @param base Настройки, которые уже действуют: провайдер, модель, адрес демона, рассуждение.
     */
    fun chatOptimizedFrom(base: LlmProviderConfig): Tuning {
        val tuned = optimizedFrom(base)
        return tuned.copy(config = tuned.config.copy(ollamaTemperature = TEMPERATURE_CHAT))
    }

    /** Профиль по имени: `null` — такого профиля нет (аргумент прогона опечатан). */
    fun byId(id: String): Tuning? = ALL.firstOrNull { it.id == id }

    /**
     * Профили с подменённым именем модели — ось «квантование».
     *
     * Подменяется только имя: окно, температура, рассуждение, инструкция и бюджет остаются
     * профильными. Иначе сравнение квантований было бы сравнением двух наборов настроек сразу,
     * и разницу в ответах нельзя было бы отнести ни к квантованию, ни к условиям ответа.
     * Пустое имя (аргумент не задан) оставляет умолчание профиля нетронутым: имя модели —
     * часть профиля, а не обязательный аргумент прогона.
     */
    fun withModel(model: String?): List<Tuning> = ALL.map { tuning ->
        if (model.isNullOrBlank()) tuning
        else tuning.copy(config = tuning.config.copy(ollamaModel = model))
    }
}
